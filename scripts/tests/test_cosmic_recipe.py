"""The `cosmic` package's generated source list matches its inputs.

package/cosmic/cosmic-sources.inc is generated by scripts/cosmic-recipe.py from the
TSV, the libcosmic pin, scripts/cosmic-locks and board/desktop/cosmic-patches, and
its COSMIC_VERSION is a digest of all of them: a change to any input is a new
version, so Buildroot rebuilds COSMIC instead of keeping a stale build dir. A stale
.inc would silently build the old set, so the gate fails on it.

Run: python3 -m pytest scripts/tests -q   (from the repo root)
"""
from __future__ import annotations

import importlib.util
import re
import subprocess
import sys
from pathlib import Path

SCRIPTS = Path(__file__).resolve().parents[1]
PKG = SCRIPTS.parent / "buildroot-external" / "package" / "cosmic"

spec = importlib.util.spec_from_file_location("recipe", SCRIPTS / "cosmic-recipe.py")
recipe = importlib.util.module_from_spec(spec)
spec.loader.exec_module(recipe)


def test_the_generated_source_list_is_current():
    r = subprocess.run([sys.executable, str(SCRIPTS / "cosmic-recipe.py"), "--check"],
                       capture_output=True, text=True)
    assert r.returncode == 0, r.stderr


def test_every_archive_is_hashed():
    hashed = set(re.findall(r"^sha256\s+[0-9a-f]{64}\s+(\S+)$",
                            (PKG / "cosmic.hash").read_text(), re.M))
    for r in recipe.rows():
        assert recipe.archive(r)[1] in hashed, r["name"]


def test_the_version_moves_with_every_input(tmp_path, monkeypatch):
    rows = recipe.rows()
    base = recipe.digest(rows)
    moved = [dict(rows[0], commit="0" * 40)] + rows[1:]
    assert recipe.digest(moved) != base, "a commit is an input"
    locks = tmp_path / "locks"
    locks.mkdir()
    for p in recipe.LOCKS.glob("*.Cargo.lock"):
        (locks / p.name).write_bytes(p.read_bytes())
    monkeypatch.setattr(recipe, "LOCKS", locks)
    monkeypatch.setattr(recipe, "REPO", tmp_path)
    monkeypatch.setattr(recipe, "PATCHES", tmp_path / "patches")
    same = recipe.digest(rows)
    first = sorted(locks.glob("*.Cargo.lock"))[0]
    first.write_text(first.read_text() + "\n")
    assert recipe.digest(rows) != same, "a lock is an input"


# What post-build.sh copied in from the host build until 2026-10-28.
SHIPPED = """cosmic-comp cosmic-session cosmic-panel cosmic-panel-button cosmic-launcher
cosmic-applets cosmic-settings cosmic-settings-daemon cosmic-notifications cosmic-osd
cosmic-osk cosmic-idle cosmic-bg cosmic-randr cosmic-screenshot cosmic-term cosmic-files
cosmic-edit cosmic-store cosmic-player cosmic-app-library cosmic-workspaces cosmic-viewer
cosmic-greeter cosmic-monitor cosmic-files-applet cosmic-greeter-daemon""".split()


def test_the_package_installs_what_post_build_used_to_copy():
    mk = (PKG / "cosmic.mk").read_text()
    installed = set(re.search(r"COSMIC_BINARIES = \\\n(.*?)\n\n", mk, re.S)
                    .group(1).replace("\\", " ").split())
    assert set(SHIPPED) <= installed, set(SHIPPED) - installed
    assert "pop-launcher-bin $(TARGET_DIR)/usr/bin/pop-launcher" in mk


def test_post_build_no_longer_copies_the_binaries():
    # A copy there would land after Buildroot's strip step and replace the package's.
    post = (SCRIPTS.parent / "buildroot-external" / "board" / "desktop"
            / "post-build.sh").read_text()
    assert not re.search(r"cp -f \S*/release/\$\{b\}", post)
    assert "pop-launcher-bin" not in post


def test_the_license_survives_legal_info():
    # Buildroot's legal-info echoes the manifest line inside single quotes; an
    # apostrophe in the license broke the 26.10.47 release's SBOM step.
    mk = (PKG / "cosmic.mk").read_text()
    lic = re.search(r"^COSMIC_LICENSE = (.*)$", mk, re.M).group(1)
    assert "'" not in lic
