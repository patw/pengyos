#!/usr/bin/env python3
"""Compose the edition defconfigs from their layers.

PengyOS editions nest: Core ⊆ Server ⊆ Desktop (README). The defconfigs used to
be hand-kept copies of each other and drifted (Server lost Core's firmware and
Python; Desktop lost Server's CLI set). Now each layer lives once in
buildroot-external/configs/layers/<layer>.config and every edition's defconfig
is GENERATED by stacking its layers (configs/layers/editions.toml):

    core                         -> pengyos_core_defconfig
    core + server                -> pengyos_server_defconfig
    core + server + desktop      -> pengyos_desktop_defconfig
    ... + nvidia                 -> pengyos_desktop_nvidia_defconfig

Rules:
  * A later layer's setting of a symbol overrides an earlier one; the earlier
    line is replaced by a comment pointing at the override.
  * The kernel fragments, rootfs overlays and post-build scripts accumulate:
    Buildroot applies each list in order, so a later layer's file wins and a
    later layer's script runs after (and can override) an earlier one's.
    Post-image scripts do not: each edition assembles its own image.

Usage:
    scripts/compose-defconfigs.py           rewrite the generated defconfigs
    scripts/compose-defconfigs.py --check   exit 1 if any is stale (tests use it)
"""
from __future__ import annotations

import re
import sys
import tomllib
from pathlib import Path

CONFIGS = Path(__file__).resolve().parent.parent / "buildroot-external" / "configs"
LAYERS = CONFIGS / "layers"
ACCUMULATE = {
    "BR2_LINUX_KERNEL_CONFIG_FRAGMENT_FILES",
    "BR2_ROOTFS_OVERLAY",
    "BR2_ROOTFS_POST_BUILD_SCRIPT",
}

_SET = re.compile(r"^(BR2_\w+)=(.*)$")
_UNSET = re.compile(r"^# (BR2_\w+) is not set\s*$")


def _setting(line: str) -> tuple[str, str] | None:
    """(symbol, value) for a setting line, value 'n' for '# X is not set'."""
    if m := _SET.match(line):
        return m[1], m[2].strip()
    if m := _UNSET.match(line):
        return m[1], "n"
    return None


def compose(name: str, layers: list[str]) -> str:
    texts = {layer: (LAYERS / f"{layer}.config").read_text().splitlines() for layer in layers}
    # Where each symbol is finally set, and the accumulated list values.
    last: dict[str, str] = {}
    lists: dict[str, list[str]] = {}
    for layer in layers:
        for line in texts[layer]:
            if s := _setting(line):
                last[s[0]] = layer
                if s[0] in ACCUMULATE:
                    for item in s[1].strip('"').split():
                        if item not in lists.setdefault(s[0], []):
                            lists[s[0]].append(item)

    out = [
        "# " + "=" * 76,
        f"# GENERATED — do not edit. {name} = {' + '.join(layers)}",
        "# Edit buildroot-external/configs/layers/*.config, then run",
        "# scripts/compose-defconfigs.py (docs: configs/layers/README.md).",
        "# " + "=" * 76,
    ]
    for layer in layers:
        out += ["", "# " + "#" * 76, f"# ## layer: {layer}", "# " + "#" * 76, ""]
        for line in texts[layer]:
            s = _setting(line)
            if s and last[s[0]] != layer:
                out.append(f"# {s[0]}: set by the {last[s[0]]} layer")
            elif s and s[0] in ACCUMULATE:
                out.append(f'{s[0]}="{" ".join(lists[s[0]])}"')
            else:
                out.append(line)
    return "\n".join(out).rstrip("\n") + "\n"


def main(argv: list[str]) -> int:
    check = "--check" in argv
    editions = tomllib.loads((LAYERS / "editions.toml").read_text())["editions"]
    stale = []
    for name, layers in editions.items():
        path = CONFIGS / name
        text = compose(name, layers)
        if path.exists() and path.read_text() == text:
            continue
        stale.append(name)
        if not check:
            path.write_text(text)
    if check and stale:
        print("stale (run scripts/compose-defconfigs.py): " + ", ".join(stale), file=sys.stderr)
        return 1
    if not check:
        print("composed: " + (", ".join(stale) if stale else "nothing changed"))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
