#!/usr/bin/env python3
"""Generate the `cosmic` Buildroot package's source list from cosmic-components.tsv.

The package (buildroot-external/package/cosmic) builds every COSMIC component in one
cargo target dir, so libcosmic, iced and wgpu compile once for the whole set, as the
host build did. Its sources are the TSV's pinned commits, fetched as GitHub archives
through Buildroot's own download step and checked against cosmic.hash.

This writes, next to the hand-written cosmic.mk:

* cosmic-sources.inc - the version, the main source, COSMIC_EXTRA_DOWNLOADS, and per
  component its commit, commit date and cargo arguments;
* cosmic.hash - the sha256 of every archive.

COSMIC_VERSION is a digest of everything the build reads from this repo (the TSV
rows, the libcosmic pin, scripts/cosmic-locks, board/desktop/cosmic-patches), so a
change to any of them is a new version and Buildroot rebuilds; nothing has to be
remembered. `--check` (run by scripts/tests) fails when the files are stale.

Usage:
  cosmic-recipe.py            regenerate (downloads each archive once to hash it)
  cosmic-recipe.py --check    exit 1 if cosmic-sources.inc is not what the inputs give
"""
from __future__ import annotations

import hashlib
import json
import sys
import urllib.request
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
TSV = REPO / "scripts" / "cosmic-components.tsv"
PIN = REPO / "scripts" / "cosmic-libcosmic.pin"
LOCKS = REPO / "scripts" / "cosmic-locks"
PATCHES = REPO / "buildroot-external" / "board" / "desktop" / "cosmic-patches"
PKG = REPO / "buildroot-external" / "package" / "cosmic"
CACHE = Path.home() / ".cache" / "pengyos-cosmic-archives"
GITHUB = "https://github.com/"


def rows() -> list[dict]:
    out = []
    for line in TSV.read_text().splitlines():
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        name, url, commit, args = (line.split("\t") + [""] * 4)[:4]
        if not url.startswith(GITHUB):
            raise SystemExit(f"{name}: {url} is not on github.com; the recipe fetches "
                             "GitHub archives")
        out.append({"name": name, "repo": url[len(GITHUB):].removesuffix(".git"),
                    "commit": commit, "args": args.strip()})
    return out


def digest(rs: list[dict]) -> str:
    h = hashlib.sha256()
    for r in rs:
        h.update(f"{r['name']}\t{r['repo']}\t{r['commit']}\t{r['args']}\n".encode())
    h.update(PIN.read_bytes())
    for p in sorted(LOCKS.glob("*.Cargo.lock")) + sorted(PATCHES.rglob("*.patch")):
        h.update(str(p.relative_to(REPO)).encode() + b"\0" + p.read_bytes())
    return h.hexdigest()[:12]


def archive(r: dict) -> tuple[str, str]:
    """(url, file name) of a component's archive at its pinned commit."""
    name = f"{r['name']}-{r['commit']}.tar.gz"
    return f"{GITHUB}{r['repo']}/archive/{r['commit']}/{name}", name


def fetch(url: str, name: str) -> bytes:
    CACHE.mkdir(parents=True, exist_ok=True)
    f = CACHE / name
    if not f.exists():
        with urllib.request.urlopen(urllib.request.Request(
                url, headers={"User-Agent": "pengyos-cosmic-recipe"}), timeout=300) as resp:
            f.write_bytes(resp.read())
    return f.read_bytes()


def commit_date(r: dict) -> str:
    url = f"https://api.github.com/repos/{r['repo']}/commits/{r['commit']}"
    with urllib.request.urlopen(urllib.request.Request(
            url, headers={"User-Agent": "pengyos-cosmic-recipe"}), timeout=60) as resp:
        return json.load(resp)["commit"]["committer"]["date"][:10]


def sources_inc(rs: list[dict], dates: dict[str, str]) -> str:
    main, rest = rs[0], rs[1:]
    url, name = archive(main)
    lines = [
        "# Generated by scripts/cosmic-recipe.py from scripts/cosmic-components.tsv,",
        "# the libcosmic pin, scripts/cosmic-locks and board/desktop/cosmic-patches.",
        "# Do not edit: change those and rerun the script.",
        "",
        f"COSMIC_VERSION = {digest(rs)}",
        f"COSMIC_SITE = {url.rsplit('/', 1)[0]}",
        f"COSMIC_SOURCE = {name}",
        "COSMIC_EXTRA_DOWNLOADS = \\",
        *[f"\t{archive(r)[0]} \\" for r in rest],
        "",
        f"COSMIC_COMPONENTS = {' '.join(r['name'] for r in rs)}",
        f"COSMIC_CARGO_COMPONENTS = {' '.join(r['name'] for r in rs if r['args'] != '-')}",
    ]
    for r in rs:
        n = r["name"]
        lines.append(f"COSMIC_COMMIT_{n} = {r['commit']}")
        lines.append(f"COSMIC_DATE_{n} = {dates[n]}")
        if r["args"] != "-":
            lines.append(f"COSMIC_CARGO_ARGS_{n} = {r['args']}")
    return "\n".join(lines) + "\n"


def current_dates() -> dict[str, str]:
    """The dates the committed .inc already records, so --check needs no network."""
    out = {}
    inc = PKG / "cosmic-sources.inc"
    if inc.exists():
        for line in inc.read_text().splitlines():
            if line.startswith("COSMIC_DATE_"):
                k, _, v = line.partition(" = ")
                out[k[len("COSMIC_DATE_"):]] = v
    return out


def main(argv: list[str]) -> int:
    rs = rows()
    if argv == ["--check"]:
        dates = current_dates()
        if set(dates) != {r["name"] for r in rs}:
            print("cosmic-sources.inc does not list every TSV component; run "
                  "scripts/cosmic-recipe.py", file=sys.stderr)
            return 1
        if (PKG / "cosmic-sources.inc").read_text() != sources_inc(rs, dates):
            print("buildroot-external/package/cosmic/cosmic-sources.inc is stale; run "
                  "scripts/cosmic-recipe.py", file=sys.stderr)
            return 1
        return 0
    known = current_dates()
    old_hashes = (PKG / "cosmic.hash").read_text() if (PKG / "cosmic.hash").exists() else ""
    dates, hashes = {}, []
    for r in rs:
        url, name = archive(r)
        dates[r["name"]] = known.get(r["name"]) if f"  {name}" in old_hashes \
            and r["name"] in known else commit_date(r)
        hashes.append(f"sha256  {hashlib.sha256(fetch(url, name)).hexdigest()}  {name}")
        print(f"{r['name']}: {r['commit'][:12]} {dates[r['name']]}")
    (PKG / "cosmic-sources.inc").write_text(sources_inc(rs, dates))
    (PKG / "cosmic.hash").write_text(
        "# Generated by scripts/cosmic-recipe.py: GitHub archives at the TSV's commits.\n"
        + "\n".join(hashes) + "\n"
        + "sha256  " + hashlib.sha256(_license(rs[0])).hexdigest()
        + f"  {rs[0]['name']}/LICENSE\n")
    return 0


def _license(main: dict) -> bytes:
    """cosmic-comp's LICENSE, read out of its archive (the package's license file)."""
    import io
    import tarfile
    url, name = archive(main)
    with tarfile.open(fileobj=io.BytesIO(fetch(url, name))) as t:
        member = next(m for m in t.getmembers() if m.name.split("/", 1)[-1] == "LICENSE")
        return t.extractfile(member).read()


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
