"""The recipe catalogue: Buildroot ``BR2_EXTERNAL`` recipe metadata.

The :mod:`.catalogue` records *which* native dependencies COSMIC may need (and
:mod:`.classify` decides which of those 2026.08 does not ship). This module
records, for each dependency that needs a recipe, the concrete data an emit
step turns into a ``package/<dep>/{Config.in,<dep>.mk,<dep>.hash}`` trio:

* :attr:`Recipe.name` — the dependency's short name, also the ``package/`` dir.
* :attr:`Recipe.version` — the pinned upstream release (``_VERSION``).
* :attr:`Recipe.url` — the canonical upstream repository URL (documentation).
* :attr:`Recipe.download_url` — the exact tarball URL Buildroot downloads for
  this pinned source (the ``_SITE`` + ``_SOURCE`` archive path). This is the
  entry point for the *hash-verify* step, which re-downloads the tarball and
  re-checks the sha256. The repository ``url`` is documentation; the
  ``download_url`` is the archive endpoint (GitHub ``/archive/refs/tags`` /
  GitLab ``/-/archive`` paths differ, so it is explicit per recipe).
* :attr:`Recipe.build_system` — ``meson`` / ``autotools`` / ``make`` / ``cargo``
  / ``none`` (data-only packages such as fonts).
* :attr:`Recipe.license` — the SPDX short identifier (``_LICENSE``).
* :attr:`Recipe.source` — the download filename (``_SOURCE``); the ``.hash``
  sibling keys off this name.
* :attr:`Recipe.hash` — the ``sha256`` of that source, hex (the ``.hash`` body).
* :attr:`Recipe.br_symbols` — the kconfig symbol(s) the recipe enables.

The catalogue is **committed data** (``data/recipes.json``), regenerated by
:func:`write_catalogue`, so the emit + lint stages build off a stable,
reviewable artifact rather than hand-typed literals.

Runtime depends only on the Python standard library.
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass, field
from enum import Enum
from pathlib import Path
from typing import Any, Iterable, Iterator

# A hex sha256 digest, as written into a ``.hash`` file.
_HASH_RE = re.compile(r"^[0-9a-f]{64}$")


class BuildSystem(str, Enum):
    """The build system a recipe's package uses.

    The spec's early prose assumed every recipe is ``meson``/``autotools``/
    ``make``; the real upstreams disagree (``greetd`` and the cosmic portal are
    Rust, the fonts ship as data). The enum is therefore exhaustive rather than
    a closed trio, and emit maps each member to the right Buildroot ``_METHOD``
    (or none, for data-only packages).
    """

    MESON = "meson"
    AUTOTOOLS = "autotools"
    MAKE = "make"
    CARGO = "cargo"
    #: Data-only package (font files); no build step, no ``_VERSION``/``_SITE``.
    NONE = "none"


@dataclass(frozen=True)
class Recipe:
    """The recipe metadata for one dependency that 2026.08 does not ship."""

    name: str
    """The dependency's short name; also the ``package/<name>/`` directory."""

    version: str
    """The pinned upstream release (``<pkg>_VERSION``). Empty for data-only."""

    url: str
    """The canonical upstream repository URL (documentation / provenance)."""

    download_url: str
    """The exact tarball URL Buildroot downloads for this pinned source.

    The archive endpoint (GitHub ``/archive/refs/tags`` / GitLab ``/-/archive``)
    differs from the repository ``url`` and from a bare ``_SITE`` + ``_SOURCE``
    concatenation, so it is explicit per recipe. The *hash-verify* step
    re-downloads from here and re-checks the sha256.
    """

    build_system: BuildSystem
    """The build system the package uses (``meson``, ``cargo``, ``none`` ...)."""

    license: str
    """The SPDX short license identifier (``<pkg>_LICENSE``)."""

    source: str
    """The download filename (``<pkg>_SOURCE``); the ``.hash`` keys off it."""

    hash: str
    """The ``sha256`` of *source*, hex (the body of the ``.hash`` sibling)."""

    br_symbols: tuple[str, ...]
    """The kconfig symbol(s) this recipe enables in a BR2_EXTERNAL tree."""

    def as_dict(self) -> dict[str, Any]:
        """JSON-serialisable view (the committed data file + ``list``).

        Identical in shape to :func:`_recipe_to_dict`: a data-only (``none``)
        recipe carries no build fields, so ``version`` / ``source`` / ``hash``
        are omitted rather than emitted as empty strings. This keeps the
        ``recipes --json`` machine view byte-for-byte equal to the committed
        ``data/recipes.json``.
        """
        return _recipe_to_dict(self)


@dataclass
class RecipeCatalogue:
    """The full recipe catalogue, in declaration order."""

    recipes: tuple[Recipe, ...] = field(default_factory=tuple)

    def __iter__(self) -> Iterator[Recipe]:
        return iter(self.recipes)

    def __len__(self) -> int:
        return len(self.recipes)

    def __getitem__(self, index: int) -> Recipe:
        return self.recipes[index]

    def by_name(self, name: str) -> Recipe | None:
        """Return the recipe named *name*, or ``None`` if the catalogue lacks it."""
        for recipe in self.recipes:
            if recipe.name == name:
                return recipe
        return None

    def filter_by_names(self, names: Iterable[str]) -> list[Recipe]:
        """Return catalogue recipes whose name is in *names* (declaration order).

        Used by emit to keep the authored catalogue decoupled from a specific
        classification: pass the current ``recipe_needed`` names and get back
        exactly the recipes to author, in a stable order.
        """
        wanted = set(names)
        return [recipe for recipe in self.recipes if recipe.name in wanted]


def _recipe_from_dict(data: dict[str, Any]) -> Recipe:
    """Build a :class:`Recipe` from its JSON representation.

    ``version`` / ``source`` / ``hash`` are absent for data-only (``none``)
    recipes, so they default to ``""`` rather than raising. ``download_url`` is
    likewise absent for a data-only recipe (no single pinned tarball to
    re-download); it is required for a *buildable* recipe.
    """
    return Recipe(
        name=data["name"],
        version=data.get("version", ""),
        url=data["url"],
        download_url=data.get("download_url", ""),
        build_system=BuildSystem(data["build_system"]),
        license=data["license"],
        source=data.get("source", ""),
        hash=data.get("hash", ""),
        br_symbols=tuple(data["br_symbols"]),
    )


def _recipe_to_dict(recipe: Recipe) -> dict[str, Any]:
    """Serialise *recipe* for the committed data file (deterministic order).

    Data-only (``none``) recipes carry no ``version`` / ``source`` / ``hash`` /
    ``download_url`` — no single pinned tarball to download — so those keys are
    omitted; only the license + symbols are meaningful for a package that ships
    font files.
    """
    ordered: dict[str, Any] = {
        "name": recipe.name,
        "url": recipe.url,
        "build_system": recipe.build_system.value,
        "license": recipe.license,
        "br_symbols": list(recipe.br_symbols),
    }
    if recipe.build_system is not BuildSystem.NONE:
        ordered["version"] = recipe.version
        ordered["source"] = recipe.source
        ordered["hash"] = recipe.hash
        ordered["download_url"] = recipe.download_url
    return ordered


def default_recipe_catalogue_path() -> Path:
    """The committed recipe catalogue, resolved relative to this package.

    Lives at the repo root under ``data/`` (a sibling of this package), two
    levels up from this module, so the tool is self-contained.
    """
    return (
        Path(__file__).resolve().parent.parent / "data" / "recipes.json"
    )


def load_catalogue(path: str | Path | None = None) -> RecipeCatalogue:
    """Load the recipe catalogue at *path* (default: the committed snapshot).

    Passing ``None`` uses :func:`.default_recipe_catalogue_path`. Raises
    :class:`FileNotFoundError` if the file is missing and :class:`ValueError` on
    malformed or duplicate entries.
    """
    resolved: Path = Path(path) if path is not None else default_recipe_catalogue_path()
    if not resolved.is_file():
        raise FileNotFoundError(f"recipe catalogue not found: {resolved}")
    data = json.loads(resolved.read_text(encoding="utf-8"))
    return _catalogue_from_data(data, resolved)


def _catalogue_from_data(data: Any, source: Path) -> RecipeCatalogue:
    """Build a catalogue from parsed JSON *data*, validating its shape."""
    if not isinstance(data, list):
        raise ValueError(f"recipe catalogue must be a JSON list, got {type(data).__name__}")
    recipes: list[Recipe] = []
    seen: set[str] = set()
    for entry in data:
        recipe = _recipe_from_dict(entry)
        if recipe.name in seen:
            raise ValueError(f"duplicate recipe name in catalogue: {recipe.name!r}")
        seen.add(recipe.name)
        _validate(recipe)
        recipes.append(recipe)
    return RecipeCatalogue(recipes=tuple(recipes))


def _validate(recipe: Recipe) -> None:
    """Raise :class:`ValueError` if *recipe* violates the catalogue invariants."""
    if not recipe.name:
        raise ValueError("recipe has no name")
    if recipe.build_system is BuildSystem.NONE:
        # A data-only package (font files) has no build step, so it pins no
        # version, source, or hash — only the license + symbols are meaningful.
        if recipe.version or recipe.source or recipe.hash:
            raise ValueError(
                f"build-system 'none' recipe {recipe.name!r} must not pin "
                "version/source/hash"
            )
    else:
        if not recipe.version:
            raise ValueError(f"recipe {recipe.name!r} has no pinned version")
        if not recipe.source:
            raise ValueError(f"recipe {recipe.name!r} has no source filename")
        if not _HASH_RE.match(recipe.hash):
            raise ValueError(
                f"recipe {recipe.name!r} hash is not a 64-hex sha256: {recipe.hash!r}"
            )
        if not recipe.download_url:
            raise ValueError(
                f"buildable recipe {recipe.name!r} has no download_url"
            )
    if not recipe.br_symbols:
        raise ValueError(f"recipe {recipe.name!r} enables no kconfig symbol")


def write_catalogue(catalogue: RecipeCatalogue, path: str | Path) -> Path:
    """Write *catalogue* to *path* as deterministic JSON (sorted keys, newline).

    Returns the path written, so callers (and the CLI) can report it.
    """
    resolved = Path(path)
    resolved.parent.mkdir(parents=True, exist_ok=True)
    payload = [_recipe_to_dict(recipe) for recipe in catalogue.recipes]
    resolved.write_text(
        json.dumps(payload, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )
    return resolved


def default_recipe_catalogue() -> RecipeCatalogue:
    """The committed recipe catalogue (default source for emit/lint)."""
    return load_catalogue()
