"""High-level guest orchestration on top of the podman/distrobox engines.

:class:`GuestManager` ties the low-level :class:`~pengyos_guest.podman.Podman`
and :class:`~pengyos_guest.distrobox.Distrobox` wrappers to the four CLI
operations:

- ``apply``  — idempotent create + provision.
- ``enter``  — exec a (guest) command / shell.
- ``export`` — write a host-side launcher for a guest app.
- ``destroy``— tear the guest down.

Everything that touches the outside world goes through the mockable
:class:`~pengyos_guest.runner.Runner`, so this stays offline-testable and the
argv that would be executed is the contract tests assert on.
"""

from __future__ import annotations

import os
from dataclasses import dataclass
from pathlib import Path
from typing import Sequence

from pengyos_guest.config import Guest
from pengyos_guest.distrobox import Distrobox
from pengyos_guest.pkgspec import install_argv
from pengyos_guest.podman import Podman
from pengyos_guest.runner import Runner, SubprocessRunner
from pengyos_guest.sandbox import SandboxError, declared_host_paths

class GuestError(Exception):
    """An external (podman/distrobox) command failed."""


_LAUNCHER_TEMPLATE = (
    "#!/bin/sh\n"
    "# Host-side launcher for {app} via the {name} PengyOS guest.\n"
    "# Generated by pengyos-guest export — do not edit by hand.\n"
    'exec distrobox enter {name} -- {app} "$@"\n'
)


def default_launcher_dir() -> Path:
    """Where ``export`` writes launchers when none is given.

    Resolution order: ``$PENGYOS_LAUNCHER_DIR``, then ``$XDG_BIN_HOME``, then
    ``$HOME/.local/bin``. All are overridable via the environment, so tests can
    point it at a temp dir.
    """
    for var in ("PENGYOS_LAUNCHER_DIR", "XDG_BIN_HOME"):
        override = os.environ.get(var)
        if override:
            return Path(override)
    return Path.home() / ".local" / "bin"


@dataclass
class ApplyResult:
    """Outcome of applying a single guest."""

    name: str
    image: str
    created: bool
    provisioned: bool
    packages: list[str]
    setup: list[str]


@dataclass
class ExportResult:
    """Outcome of exporting a single launcher."""

    name: str
    app: str
    launcher_path: Path


class GuestManager:
    """Orchestrates podman + distrobox for a set of guests."""

    def __init__(self, runner: Runner | None = None) -> None:
        self._runner = runner if runner is not None else SubprocessRunner()
        self.podman = Podman(self._runner)
        self.distrobox = Distrobox(self._runner)

    @property
    def runner(self) -> Runner:
        return self._runner

    def _lock_sandbox(self, guest: Guest) -> None:
        """Restrict the runner's sandbox guard to *guest*'s declared mounts.

        A no-op when the runner has no guard (the default). When a guard is
        present, its allowlist is set to exactly the host paths this guest is
        allowed to reference, so any command that points at an undeclared host
        path is rejected before it runs.
        """
        guard = self._runner.guard
        if guard is not None:
            guard.set_allowlist(declared_host_paths([guest]))

    # -- apply --------------------------------------------------------------

    def container_exists(self, name: str) -> bool:
        """True if a container called *name* currently exists."""
        return self.podman.container_exists(name)

    def apply(self, guest: Guest, *, stream: bool = False) -> ApplyResult:
        """Create (if needed) and provision *guest*.

        Idempotent: if the container already exists the create step is skipped;
        provisioning always runs (package installs are idempotent). Returns an
        :class:`ApplyResult` describing what actually happened so callers (and
        tests) can see the create/provision decisions.

        ``setup`` commands run after the packages, inside the guest as the
        user, through ``sh -lc`` — they run on every apply, so they must be
        idempotent (``command -v rustup || ...``). With *stream* the output of
        podman, the package manager and the setup commands goes straight to the
        terminal (image pulls and installs take minutes).
        """
        # Lock the sandbox to this guest's declared mounts before touching the
        # runner: every command applied here is then checked against exactly
        # the host paths this guest is allowed to reference.
        self._lock_sandbox(guest)

        try:
            created = not self.container_exists(guest.name)
            if created:
                create_result = self.distrobox.create(
                    guest.name, guest.image, guest.mounts,
                    nvidia=guest.nvidia, stream=stream,
                )
                if not create_result.ok:
                    raise GuestError(
                        f"failed to create guest {guest.name!r}: "
                        f"{create_result.stderr.strip() or 'exit code ' + str(create_result.returncode)}"
                    )

            provisioned = bool(guest.packages)
            if provisioned:
                provision_result = self.distrobox.enter(
                    guest.name,
                    command=install_argv(guest.image, guest.packages),
                    stream=stream,
                )
                if not provision_result.ok:
                    raise GuestError(
                        f"failed to provision guest {guest.name!r}: "
                        f"{provision_result.stderr.strip() or 'exit code ' + str(provision_result.returncode)}"
                    )
            for step in guest.setup:
                step_result = self.distrobox.enter(
                    guest.name, command=["sh", "-lc", step], stream=stream
                )
                if not step_result.ok:
                    raise GuestError(
                        f"setup step failed in guest {guest.name!r}: {step}: "
                        f"{step_result.stderr.strip() or 'exit code ' + str(step_result.returncode)}"
                    )
        except SandboxError as exc:
            raise GuestError(str(exc)) from None

        return ApplyResult(
            name=guest.name,
            image=guest.image,
            created=created,
            provisioned=provisioned,
            packages=list(guest.packages),
            setup=list(guest.setup),
        )

    # -- enter --------------------------------------------------------------

    def enter(self, name: str, command: Sequence[str] | None = None):
        """``distrobox enter <name>`` (an interactive login shell) or
        ``distrobox enter <name> -- <cmd...>``, attached to the terminal.

        distrobox execs a command directly, without a login shell, so the
        guest's ``/etc/profile.d`` PATH (cargo, uv) would not apply; the command
        runs through ``sh -lc 'exec "$@"'`` instead, argv passed untouched."""
        if command:
            command = ["sh", "-lc", 'exec "$@"', "pengyos-guest", *command]
        return self.distrobox.enter(name, command=command, stream=True)

    # -- export -------------------------------------------------------------

    def export(
        self,
        name: str,
        app: str,
        *,
        launcher_dir: str | os.PathLike[str] | None = None,
    ) -> ExportResult:
        """Register *app* with distrobox and write a host-side launcher.

        The launcher is a small ``sh`` script that execs
        ``distrobox enter <name> -- <app>``; it references the guest by name so
        the launcher is self-contained. *launcher_dir* defaults to
        :func:`default_launcher_dir`.
        """
        base = Path(launcher_dir) if launcher_dir is not None else default_launcher_dir()
        launcher_path = base / app

        # A GUI app also gets a desktop entry in the host menu via
        # distrobox-export; for a plain command that finds no .desktop file and
        # fails, which is fine — the launcher below is what makes it runnable.
        self.distrobox.export_app(name, app)
        launcher_path.parent.mkdir(parents=True, exist_ok=True)
        launcher_path.write_text(
            _LAUNCHER_TEMPLATE.format(name=name, app=app), encoding="utf-8"
        )
        launcher_path.chmod(0o755)

        return ExportResult(name=name, app=app, launcher_path=launcher_path)

    # -- destroy ------------------------------------------------------------

    def destroy(self, name: str) -> None:
        """Tear down *name*: ``distrobox rm --force`` stops and removes the
        container. The user's home is shared with the host, so nothing in it
        is lost. Idempotent: an already-gone guest is not an error."""
        if self.container_exists(name):
            self.distrobox.destroy(name)


