"""The committed edition defconfigs match their layers (configs/layers/).

The defconfigs pengyos-build configures are generated by
scripts/compose-defconfigs.py; a hand edit (or a stale compose) would build
something other than what the layers say.
"""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parents[3]
COMPOSE = REPO / "scripts" / "compose-defconfigs.py"


@pytest.mark.skipif(not COMPOSE.is_file(), reason="not inside the PengyOS repo")
def test_generated_defconfigs_are_current():
    result = subprocess.run(
        [sys.executable, str(COMPOSE), "--check"], capture_output=True, text=True
    )
    assert result.returncode == 0, result.stderr
