"""Emit Buildroot config fragments and reports from a :class:`Pins` document.

The ``emit`` CLI subcommand (see ``pengyos_pins.cli``) turns a validated
:class:`Pins` manifest into two machine- and human-readable artefacts:

* a **Buildroot config fragment** — the ``CONFIG_<SYMBOL>=y`` lines that PengyOS
  would append to its Buildroot ``.config``, and
* a **report** — a Markdown human-readable summary or a JSON document.

All emitters are **deterministic**: components are always emitted in
name-sorted order, so the same input always produces byte-identical output.
The Buildroot fragment is also **re-parseable**: :func:`parse_buildroot_fragment`
recovers the emitted symbols, so an emit → parse round-trip is lossless.
"""

from __future__ import annotations

import json
import re
from typing import Sequence

from .schema import Component, Pins

#: The buildroot-fragment format identifier.
FORMAT_BUILDROOT = "buildroot-fragment"
#: The Markdown human-readable report format identifier.
FORMAT_REPORT = "report"
#: The machine-readable JSON report format identifier.
FORMAT_JSON = "json"

#: All formats :func:`emit` accepts, in the order shown to the user.
ALL_FORMATS: tuple[str, ...] = (FORMAT_BUILDROOT, FORMAT_REPORT, FORMAT_JSON)

#: A single ``CONFIG_<SYMBOL>=<value>`` line from a Buildroot fragment.  The
#: value may be ``y``, ``m``, ``=n`` (built-in), or any Buildroot token.
_CONFIG_RE = re.compile(r"^\s*(CONFIG_[A-Za-z0-9_]+)\s*=\s*(\S+)\s*$")


def _symbol(name: str) -> str:
    """Return the Buildroot config symbol for a component name.

    Buildroot config symbols allow only ``[A-Za-z0-9_]``; component names use
    ``[a-z0-9][a-z0-9_-]*``.  So the mapping upper-cases the name and turns
    dashes into underscores: ``linux-libre`` -> ``CONFIG_LINUX_LIBRE``.
    """
    return name.upper().replace("-", "_")


# --------------------------------------------------------------------------- #
# Buildroot config fragment
# --------------------------------------------------------------------------- #


def buildroot_fragment(pins: Pins) -> str:
    """Return the Buildroot ``.config`` fragment for ``pins``.

    One ``CONFIG_<SYMBOL>=y`` line per component, in name-sorted order, preceded
    by a short header comment.  The output is deterministic and
    :func:`parse_buildroot_fragment`-able.
    """
    lines = [
        "# Generated by pengyos-pins — PengyOS Buildroot config fragment",
        "# One 'CONFIG_<SYMBOL>=y' line per pinned component (name-sorted).",
        "",
    ]
    for component in sorted(pins.components, key=lambda c: c.name):
        symbol = _symbol(component.name)
        lines.append(f"CONFIG_{symbol}=y")
    lines.append("")  # trailing newline
    return "\n".join(lines)


def parse_buildroot_fragment(text: str) -> list[str]:
    """Recover the ``CONFIG_<SYMBOL>`` symbols from a Buildroot fragment.

    Comment lines (starting with ``#``) and blank lines are ignored.  Returns
    the symbols in the order they appear (which, from
    :func:`buildroot_fragment`, is name-sorted).
    """
    symbols: list[str] = []
    for line in text.splitlines():
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        match = _CONFIG_RE.match(line)
        if match:
            symbols.append(match.group(1))
    return symbols


# --------------------------------------------------------------------------- #
# Reports
# --------------------------------------------------------------------------- #


def _component_dict(component: Component) -> dict:
    """Return a plain dict copy of a component's fields."""
    return {
        "name": component.name,
        "upstream": component.upstream,
        "version": component.version,
        "url": component.url,
        "sha256": component.sha256,
        "license": component.license,
        "edition": component.edition,
    }


def _report_table(components: Sequence[Component]) -> str:
    """Return the Markdown table body for ``components`` (already ordered)."""
    header = "| name | upstream | version | license | edition | sha256 |"
    separator = "| --- | --- | --- | --- | --- | --- |"
    rows = []
    for component in components:
        edition = component.edition or "-"
        rows.append(
            f"| {component.name} | {component.upstream} | {component.version} "
            f"| {component.license} | {edition} | {component.sha256} |"
        )
    return "\n".join([header, separator, *rows])


def emit_report(pins: Pins) -> str:
    """Return the Markdown human-readable report for ``pins``."""
    components = sorted(pins.components, key=lambda c: c.name)
    editions = pins.edition_names
    edition_line = ", ".join(editions) if editions else "(none assigned)"
    lines = [
        "# PengyOS pins report",
        "",
        f"- Components: {len(components)}",
        f"- Editions: {edition_line}",
        "",
        _report_table(components),
        "",
    ]
    return "\n".join(lines)


def emit_json(pins: Pins) -> str:
    """Return the JSON report for ``pins`` (pretty-printed, deterministic)."""
    payload = {
        "component_count": len(pins),
        "editions": pins.edition_names,
        "components": [
            _component_dict(c)
            for c in sorted(pins.components, key=lambda c: c.name)
        ],
    }
    return json.dumps(payload, indent=2, sort_keys=True) + "\n"


def emit(pins: Pins, fmt: str) -> str:
    """Dispatch to the emitter for ``fmt``.

    ``fmt`` is one of :data:`ALL_FORMATS` (``buildroot-fragment``, ``report``,
    ``json``).  Raises :class:`ValueError` for any other value.
    """
    if fmt == FORMAT_BUILDROOT:
        return buildroot_fragment(pins)
    if fmt == FORMAT_REPORT:
        return emit_report(pins)
    if fmt == FORMAT_JSON:
        return emit_json(pins)
    raise ValueError(
        f"unknown format: {fmt!r} (expected one of {', '.join(ALL_FORMATS)})"
    )
