"""The first-boot provisioning renderer.

``provision`` renders the *first-boot* steps that make a freshly written PengyOS
slot a usable host: the ``/etc/fstab`` that wires the slots + data partition into
the root filesystem, the hostname, the user accounts and their authorized SSH
keys, and the network manager. It consumes the validated
:class:`~pengyos_install.models.ProvisionConfig` (``install.toml``) and the
target :class:`~pengyos_install.models.Layout` (the fstab needs the partition
paths), plus the active slot (which root the fstab lists first — the release
names it).

This is the engine the ``pengyos-install provision-plan`` CLI drives, and the
same first-boot plan the ``install`` engine emits as its trailing
``provision-plan`` step. It is **pure** (no I/O, no shell, no side effects) so it
is golden-testable: for a fixed (config, layout, active-slot) triple the rendered
steps are byte-stable.

## How file content is pinned

Every file the renderer writes is emitted as two ordered steps so the content is
*exact* and reviewable:

1. ``install -d '<dir>'`` — ensure the parent directory exists (``.ssh`` must be
   mode 0700, ``/etc`` already does, …).
2. ``printf '%s' '<content>' > '<path>'`` — write the content verbatim. The
   content is single-quoted for the shell, so it is written byte-for-byte; a
   literal ``'`` inside the content is rendered as ``'\''`` (the POSIX idiom).

Writing the content through ``printf`` (rather than a bare ``echo``) keeps the
bytes exact — no trailing newline is added, no backslash is interpreted.
``authorized_keys`` in particular must not gain a spurious trailing newline.

## The first-boot plan, in order

::

    fstab      write /etc/fstab (active slot, ESP, data partitions)
    hostname   write /etc/hostname
    users      add each user, then write their authorized_keys
    network    enable the declared network manager
"""

from __future__ import annotations

from pengyos_install.models import Layout, Plan, ProvisionConfig, Step

__all__ = [
    "ProvisionBuilder",
    "render_provision",
    "fstab_content",
]


class ProvisionBuilder:
    """Accumulate :class:`Step`s into an ordered :class:`Plan`.

    A thin, explicit builder so the first-boot step order is readable and each
    phase is a named method (easy to extend / unit-test in isolation). Mirrors
    :class:`~pengyos_install.plan.PlanBuilder`.
    """

    def __init__(self) -> None:
        self._steps: list[Step] = []

    def add(
        self,
        argv,
        *,
        description: str = "",
    ) -> "ProvisionBuilder":
        """Append a step (return ``self`` for chaining).

        *argv* may be a :class:`Step` (already built) or a sequence of argv
        parts (built via :meth:`Step.from_argv`).
        """
        if isinstance(argv, Step):
            self._steps.append(argv)
        else:
            self._steps.append(Step.from_argv(argv, description=description))
        return self

    def plan(self) -> Plan:
        """Materialise the accumulated steps into a :class:`Plan`."""
        return Plan.from_steps(self._steps)


def _write_dir_step(path: str, *, description: str) -> Step:
    """Ensure the parent directory *path* exists (``install -d``)."""
    return Step.from_argv(
        ["install", "-d", path],
        description=description,
    )


def _write_file_step(path: str, content: str, *, description: str) -> Step:
    """Write *content* to *path* byte-for-byte.

    The content goes to **stdout** via ``printf '%s'`` — a clean argv (no shell
    metacharacter). The shell script renderer appends ``> '<path>'`` (via the
    step's ``redirect``), so the file is written exactly as rendered. The
    content is single-quoted for the shell, so it is written byte-for-byte; a
    literal ``'`` inside the content is rendered as ``'\''`` (the POSIX idiom).
    Using ``printf`` (rather than a bare ``echo``) keeps the bytes exact — no
    trailing newline is added, no backslash is interpreted.
    """
    return Step.from_argv(
        ["printf", "%s", content],
        description=description,
        redirect=path,
    )


def fstab_content(layout: Layout, active_slot: str) -> str:
    """Render the ``/etc/fstab`` that wires the slots + data into the root fs.

    The active slot is listed first (it is where the kernel boots from); the ESP
    is mounted at ``/boot/EFI`` and the data partition at ``/data`` (where the
    machine-specific ``/var`` / ``/home`` state lives — see the install/update
    architecture). Entries are ordered deterministically (active slot, ESP,
    data).
    """
    active = layout.slot(active_slot)
    lines = [
        "# /etc/fstab — generated by pengyos-install provision-plan",
        "# <source> <mount point> <type> <options> <dump> <pass>",
        f"{active.partition}  /  ext4  defaults  0 1",
        f"{layout.esp.partition}  /boot/EFI  fat  defaults  0 2",
        f"{layout.data.partition}  /data  btrfs  defaults  0 2",
    ]
    return "\n".join(lines) + "\n"


def render_provision(
    config: ProvisionConfig,
    layout: Layout,
    active_slot: str,
) -> Plan:
    """Render the ordered first-boot provisioning steps.

    Pure: no I/O, no shell, no side effects. Deterministic for a fixed
    (config, layout, active-slot) triple — the rendered plan is
    golden/reproducible.

    Steps, in order: ``fstab`` (write ``/etc/fstab``), ``hostname`` (write
    ``/etc/hostname``), ``users`` (add each user, then write their
    ``authorized_keys``), ``network`` (enable the declared network manager).
    """
    builder = ProvisionBuilder()
    _fstab_steps(layout, active_slot, builder)
    _hostname_steps(config, builder)
    _users_steps(config, builder)
    _network_steps(config, builder)
    return builder.plan()


def _fstab_steps(
    layout: Layout, active_slot: str, builder: ProvisionBuilder
) -> None:
    """Phase 1: write ``/etc/fstab`` (active slot, ESP, data)."""
    content = fstab_content(layout, active_slot)
    builder.add(
        _write_dir_step("/etc", description="ensure /etc exists"),
    )
    builder.add(
        _write_file_step(
            "/etc/fstab", content, description="write /etc/fstab"
        ),
    )


def _hostname_steps(
    config: ProvisionConfig, builder: ProvisionBuilder
) -> None:
    """Phase 2: write ``/etc/hostname``."""
    content = config.hostname + "\n"
    builder.add(
        _write_dir_step("/etc", description="ensure /etc exists"),
    )
    builder.add(
        _write_file_step(
            "/etc/hostname", content, description="write /etc/hostname"
        ),
    )


def _users_steps(
    config: ProvisionConfig, builder: ProvisionBuilder
) -> None:
    """Phase 3: add each user, then write their ``authorized_keys``."""
    for user in config.users:
        argv = ["useradd", "--create-home", "--shell", user.shell]
        # Omit ``--groups`` when the user has none (a bare ``--groups ''`` is
        # noise / can trip up useradd).
        if user.groups:
            argv += ["--groups", ",".join(user.groups)]
        argv.append(user.name)
        builder.add(argv, description=f"add user {user.name}")
        if user.ssh_keys:
            content = "\n".join(user.ssh_keys) + "\n"
            builder.add(
                _write_dir_step(
                    f"/home/{user.name}/.ssh",
                    description=f"ensure {user.name}'s .ssh dir exists",
                ),
            )
            builder.add(
                _write_file_step(
                    f"/home/{user.name}/.ssh/authorized_keys",
                    content,
                    description=f"install {user.name}'s authorized_keys",
                ),
            )


def _network_steps(
    config: ProvisionConfig, builder: ProvisionBuilder
) -> None:
    """Phase 4: enable the declared network manager."""
    manager = config.network.manager
    builder.add(
        ["systemctl", "enable", f"{manager}"],
        description=f"enable the {manager} network manager",
    )
