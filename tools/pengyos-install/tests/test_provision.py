def test_user_add_args_shell_and_groups(install_toml, layout_json):
    plan = _plan(install_toml, layout_json)
    add = plan[4]
    assert add.argv[0] == "useradd"
    assert "--create-home" in add.argv
    assert "--shell" in add.argv
    assert "/bin/bash" in add.argv
    assert "--groups" in add.argv
    assert "wheel,audio,video" in add.argv
