# --------------------------------------------------------------------------- #
# Integration: the rendered script actually writes the files (opt-in)
# --------------------------------------------------------------------------- #
def _execute_provision_script(root: "pathlib.Path", script: str) -> None:
    """Run the rendered provision script against a fake root.

    Absolute paths are rewritten into *root*; ``useradd`` / ``systemctl`` (which
    need root/a real system) are stubbed as no-ops on a stub ``PATH``. Verifies
    the rendered script — content to stdout via ``printf``, shell-redirected —
    writes each file byte-for-byte.
    """
    import os
    import subprocess
    import textwrap

    (root / "etc").mkdir(parents=True, exist_ok=True)
    stub = root / "stubbin"
    stub.mkdir(exist_ok=True)
    for bin_name in ("useradd", "systemctl"):
        (stub / bin_name).write_text(
            textwrap.dedent(
                """\
                #!/usr/bin/env bash
                exit 0
                """
            ),
            encoding="utf-8",
        )
        (stub / bin_name).chmod(0o755)

    rewritten = script.replace("> /", f"> {root}/").replace(
        "install -d /", f"install -d {root}/"
    )
    env = dict(os.environ, PATH=f"{stub}:{os.environ['PATH']}")
    result = subprocess.run(
        ["bash", "-c", rewritten],
        env=env,
        capture_output=True,
        text=True,
    )
    assert result.returncode == 0, result.stderr


def test_rendered_script_writes_files_byte_exact(
    integration, tmp_path, install_toml, layout_json
):
    """PENGYOS_IT=1: execute the rendered script against a fake root and assert
    every file is written byte-for-byte (the end-to-end contract)."""
    import pathlib

    if not integration:
        pytest.skip("integration test (PENGYOS_IT=1)")

    root = tmp_path / "root"
    cfg = ProvisionConfig.from_toml(install_toml)
    layout = Layout.from_json(layout_json)
    plan = render_provision(cfg, layout, "a")
    script = plan.to_shell_script()

    _execute_provision_script(root, script)

    assert (root / "etc" / "fstab").read_text(encoding="utf-8") == FSTAB
    assert (root / "etc" / "hostname").read_text(encoding="utf-8") == HOSTNAME
    auth = root / "home" / "alex" / ".ssh" / "authorized_keys"
    assert auth.read_text(encoding="utf-8") == AUTHORIZED_KEYS
