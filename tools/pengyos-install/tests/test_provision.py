# --------------------------------------------------------------------------- #
# Every step is a shell-quotable argv (round-trips through shlex)
# --------------------------------------------------------------------------- #
def test_every_step_argv_is_shell_quotable(install_toml, layout_json):
    """Each argv, shlex-joined, round-trips back to the identical argv — the
    contract the install engine relies on (no shell string, clean argv)."""
    plan = _plan(install_toml, layout_json)
    for step in plan:
        joined = step.shlex_join()
        assert shlex.split(joined) == list(step.argv)


