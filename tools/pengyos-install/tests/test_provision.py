# CLI: provision-plan
# --------------------------------------------------------------------------- #
def _run(argv, *, out=None, err=None):
    buf = io.StringIO() if out is None else out
    errbuf = io.StringIO() if err is None else err
    code = cli.main(argv, out=buf, err=errbuf)
    return code, buf.getvalue(), errbuf.getvalue()


def test_cli_provision_shell_script(tmp_path, install_toml, layout_json):
    cfg = tmp_path / "install.toml"
    lay = tmp_path / "layout.json"
    cfg.write_text(install_toml, encoding="utf-8")
    lay.write_text(layout_json, encoding="utf-8")
    code, out, _ = _run(
        ["provision-plan", "--config", str(cfg), "--layout", str(lay)]
    )
    assert code == 0
    assert out.startswith("#!/usr/bin/env bash")
    # the fstab content is embedded verbatim (multi-line, single-quoted)
    assert FSTAB.splitlines()[2] in out
    # the hostname is written
    assert "alex-pengyos" in out
    # the useradd + systemctl steps are present
    assert "useradd" in out
    assert "systemctl enable systemd" in out


