def test_user_without_ssh_keys_writes_no_auth_keys(install_toml, layout_json):
    """The `root` user has no keys → no .ssh/authorized_keys step for it."""
    plan = _plan(install_toml, layout_json)
    authkeys = [s for s in plan if "authorized_keys" in s.redirect]
    # only alex (who has a key) gets an authorized_keys step
    assert len(authkeys) == 1
    assert authkeys[0].redirect == "/home/alex/.ssh/authorized_keys"


def test_authorized_keys_written_exact_content(install_toml, layout_json):
    plan = _plan(install_toml, layout_json)
    write = [s for s in plan if "authorized_keys" in s.redirect][0]
    assert write.argv[2] == AUTHORIZED_KEYS
    assert write.redirect == "/home/alex/.ssh/authorized_keys"
    # .ssh dir is ensured right before the keys are written
    before = plan.steps[plan.steps.index(write) - 1]
    assert list(before.argv) == ["install", "-d", "/home/alex/.ssh"]


def test_ssh_key_content_is_trailing_newline_terminated(install_toml, layout_json):
    """authorized_keys ends in exactly one newline (no double/trailing junk)."""
    plan = _plan(install_toml, layout_json)
    write = [s for s in plan if "authorized_keys" in s.redirect][0]
    assert write.argv[2].endswith("\n")
    assert not write.argv[2].endswith("\n\n")


def test_content_with_single_quote_roundtrips_through_shell(tmp_path):
    """A literal single quote in content survives the shell render (shlex.quote
    escapes it as ``'\''``) and writes byte-for-byte — the printf-to-stdout +
    redirect mechanism must not corrupt it."""
    import subprocess

    dest = tmp_path / "quote"
    step = Step.from_argv(["printf", "%s", "it's a test"], redirect=str(dest))
    # the rendered line is a valid shell command that writes the exact content
    script = f"{step.shlex_join()} > {dest}"
    result = subprocess.run(["bash", "-c", script], capture_output=True, text=True)
    assert result.returncode == 0, result.stderr
    assert dest.read_text() == "it's a test"
    # and the argv stays clean (no metacharacter, content to stdout)
    assert step.argv == ("printf", "%s", "it's a test")
    assert step.redirect == str(dest)


