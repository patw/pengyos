"""Tests for the first-boot provisioning renderer.

``provision`` renders the *first-boot* steps that make a freshly written PengyOS
slot a usable host: ``/etc/fstab``, ``/etc/hostname``, the user accounts + their
authorized SSH keys, and the network manager. It consumes the validated
:class:`~pengyos_install.models.ProvisionConfig` (``install.toml``) and the
target :class:`~pengyos_install.models.Layout` (the fstab needs the partition
paths), plus the active slot (which root the fstab lists first).

The fixtures (``install_toml``, ``layout_json``) live in ``conftest.py``. The
renderer is pure, so the plan is golden-testable: for a fixed (config, layout,
active-slot) triple the rendered steps are byte-stable.
"""

from __future__ import annotations

import io
import shlex

import pytest

from pengyos_install import cli
from pengyos_install.models import Layout, ProvisionConfig, Step
from pengyos_install.provision import fstab_content, render_provision


# The exact /etc/fstab the fixture layout + active slot 'a' renders.
FSTAB = (
    "# /etc/fstab — generated by pengyos-install provision-plan\n"
    "# <source> <mount point> <type> <options> <dump> <pass>\n"
    "/dev/sda2  /  ext4  defaults  0 1\n"
    "/dev/sda1  /boot/EFI  fat  defaults  0 2\n"
    "/dev/sda4  /data  btrfs  defaults  0 2\n"
)

# The exact /etc/hostname the fixture renders (hostname + trailing newline).
HOSTNAME = "alex-pengyos\n"

# The exact authorized_keys the fixture user renders (key + trailing newline).
AUTHORIZED_KEYS = (
    "ssh-ed25519 AAECAwQFBgcICQoLDA0ODxAREhMUFRYXGBkaGxwdHh8= "
    "example@alex\n"
)


# --------------------------------------------------------------------------- #
# fstab
# --------------------------------------------------------------------------- #
def test_fstab_content_is_golden(install_toml, layout_json):
    """The fstab lists the active slot, the ESP, and the data, in order."""
    layout = Layout.from_json(layout_json)
    assert fstab_content(layout, "a") == FSTAB


def test_fstab_root_entry_follows_active_slot(layout_json):
    """The fstab's first (root) entry is the active slot; flip the slot."""
    layout = Layout.from_json(layout_json)
    a = fstab_content(layout, "a").splitlines()[2]
    b = fstab_content(layout, "b").splitlines()[2]
    assert a == "/dev/sda2  /  ext4  defaults  0 1"
    assert b == "/dev/sda3  /  ext4  defaults  0 1"


def test_fstab_lists_esp_and_data(layout_json):
    layout = Layout.from_json(layout_json)
    text = fstab_content(layout, "a")
    assert "/dev/sda1  /boot/EFI  fat  defaults  0 2" in text
    assert "/dev/sda4  /data  btrfs  defaults  0 2" in text


# --------------------------------------------------------------------------- #
# Golden first-boot plan (the whole render)
# --------------------------------------------------------------------------- #
def _plan(install_toml, layout_json, slot="a"):
    config = ProvisionConfig.from_toml(install_toml)
    layout = Layout.from_json(layout_json)
    return render_provision(config, layout, slot)


def test_provision_step_count_and_phases(install_toml, layout_json):
    """fstab(2) + hostname(2) + users(3: alex add + .ssh + authkeys;
    root add) + network(1) = 9."""
    plan = _plan(install_toml, layout_json)
    assert len(plan) == 9

    argv0 = [s.argv[0] for s in plan]
    # fstab/hostname phases open with `install -d /etc` then `printf`; the
    # users phase opens with `useradd`; the network phase is last.
    assert argv0[0] == "install"
    assert argv0[4] == "useradd"
    assert argv0[-1] == "systemctl"


def test_provision_order_fstab_hostname_users_network(install_toml, layout_json):
    plan = _plan(install_toml, layout_json)
    # first two steps write /etc/fstab, next two write /etc/hostname
    assert plan[0].description == "ensure /etc exists"
    assert plan[1].description == "write /etc/fstab"
    assert plan[2].description == "ensure /etc exists"
    assert plan[3].description == "write /etc/hostname"
    # users phase, then network last
    assert plan[4].description == "add user alex"
    assert plan[7].description == "add user root"
    assert plan[8].description.startswith("enable the")


def test_provision_is_deterministic(install_toml, layout_json):
    a = _plan(install_toml, layout_json)
    b = _plan(install_toml, layout_json)
    assert a.to_json() == b.to_json()
    assert a.to_shell_script() == b.to_shell_script()


def test_provision_json_roundtrips(install_toml, layout_json):
    from pengyos_install.models import Plan

    plan = _plan(install_toml, layout_json)
    assert Plan.from_json(plan.to_json()) == plan


# --------------------------------------------------------------------------- #
# fstab / hostname steps write exact content
# --------------------------------------------------------------------------- #
def test_fstab_step_writes_exact_content(install_toml, layout_json):
    plan = _plan(install_toml, layout_json)
    write = plan[1]
    assert write.argv[0] == "printf"
    assert write.argv[1] == "%s"
    # content goes to stdout (clean argv); the shell redirects it to the file
    assert write.argv[2] == FSTAB
    assert write.redirect == "/etc/fstab"


def test_hostname_step_writes_exact_content(install_toml, layout_json):
    plan = _plan(install_toml, layout_json)
    write = plan[3]
    assert write.argv[2] == HOSTNAME
    assert write.redirect == "/etc/hostname"


def test_write_dir_precedes_write_file(install_toml, layout_json):
    """Each file is written: `install -d <dir>` first, then `printf ... > file`."""
    plan = _plan(install_toml, layout_json)
    # fstab: step 0 = install -d /etc, step 1 = printf ... > /etc/fstab
    assert list(plan[0].argv) == ["install", "-d", "/etc"]
    # hostname: step 2 = install -d /etc, step 3 = printf ... > /etc/hostname
    assert list(plan[2].argv) == ["install", "-d", "/etc"]


