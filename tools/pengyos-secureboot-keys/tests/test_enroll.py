"""Tests for the ``enroll-commands`` feature.

These pin down the contract ``spec.md`` "Verification" promises: golden,
deterministic enrollment commands for ``cert-to-efi-sig-list`` / ``efi-sig-list``,
a machine-readable JSON variant, correct ordering, fail-closed on a missing
certificate, and the no-key-material-leak invariant.
"""

import json
import os
import shlex
from pathlib import Path

import pytest

from pengyos_sbkeys import cli
from pengyos_sbkeys.enroll import (
    EnrollmentError,
    build_enrollment,
    enroll_commands,
    render_json,
    render_shell,
)
from pengyos_sbkeys.keys import (
    KEY_FILES,
    KEY_NAMESPACE,
    VARIABLE_FOR_ROLE,
    guid_for,
    is_private,
    variable_for_role,
)

# The exact golden output for `--keys keys`. Kept as a literal so the golden
# test is an unambiguous byte-for-byte comparison.
GOLDEN_SHELL = """\
#!/bin/sh
# Generated by `pengyos-sbkeys enroll-commands`.
# Enrolls the PengyOS PK/KEK/db Secure Boot keys into the firmware EFI
# variables with sbsigntools. Run as root (prefix with sudo) on the
# target machine.

# --- Enroll PK into PK ---
# Convert PK.cert to an EFI signature list (PK.sig).
cert-to-efi-sig-list -g a5959556-435d-5461-a310-6cf0e61ebb05 keys/PK.cert keys/PK.sig
# Append the signature to the PK EFI variable.
efi-sig-list -a PK a5959556-435d-5461-a310-6cf0e61ebb05 keys/PK.sig

# --- Enroll KEK into KEK ---
# Convert KEK.cert to an EFI signature list (KEK.sig).
cert-to-efi-sig-list -g d6f0de74-75ef-5d80-8761-0060fc6549cd keys/KEK.cert keys/KEK.sig
# Append the signature to the KEK EFI variable.
efi-sig-list -a KEK d6f0de74-75ef-5d80-8761-0060fc6549cd keys/KEK.sig

# --- Enroll DB into db ---
# Convert DB.cert to an EFI signature list (DB.sig).
cert-to-efi-sig-list -g 4387c61f-0e93-5522-9897-9eb8b301b984 keys/DB.cert keys/DB.sig
# Append the signature to the db EFI variable.
efi-sig-list -a db 4387c61f-0e93-5522-9897-9eb8b301b984 keys/DB.sig
"""


def _make_keys_dir(tmp_path: Path) -> Path:
    """Create a ``keys`` dir with a dummy public cert per role.

    The contents are irrelevant -- enrollment only needs the files to exist --
    so empty files stand in for the certificates. Returns the *relative*
    ``keys`` path so the rendered output is deterministic.
    """
    keys = tmp_path / "keys"
    keys.mkdir()
    for key_file in KEY_FILES:
        if not is_private(key_file):
            (keys / key_file.name).write_bytes(b"-----BEGIN CERTIFICATE-----\n")
    return keys


# --- GUID / variable policy -------------------------------------------------


def test_guids_are_deterministic_v5():
    # Same role -> same GUID, every run.
    for role in ("PK", "KEK", "DB"):
        assert guid_for(role) == guid_for(role)
        # RFC 4122 version 5 => the version nibble is 5.
        assert guid_for(role)[14] == "5"


def test_guids_are_derived_from_project_namespace():
    for role in ("PK", "KEK", "DB"):
        import uuid

        expected = str(uuid.uuid5(KEY_NAMESPACE, f"pengyos-secureboot-keys:{role}"))
        assert guid_for(role) == expected


def test_role_maps_to_expected_efi_variable():
    assert VARIABLE_FOR_ROLE == {"PK": "PK", "KEK": "KEK", "DB": "db"}
    for key_file in KEY_FILES:
        if not is_private(key_file):
            assert variable_for_role(key_file.role) == VARIABLE_FOR_ROLE[key_file.role]


# --- build_enrollment -------------------------------------------------------


def test_build_enrollment_order_is_pk_kek_db(tmp_path):
    keys = _make_keys_dir(tmp_path)
    steps = build_enrollment(keys)
    assert [s.role for s in steps] == ["PK", "KEK", "DB"]


def test_build_enrollment_paths_and_commands(tmp_path, monkeypatch):
    _make_keys_dir(tmp_path)
    monkeypatch.chdir(tmp_path)
    steps = build_enrollment(Path("keys"))
    roles = {s.role: s for s in steps}

    # Cert / sig paths are built from the relative `keys` argument.
    assert str(roles["PK"].cert) == "keys/PK.cert"
    assert str(roles["PK"].sig) == "keys/PK.sig"

    # Each step carries exactly the two expected commands.
    for role, step in roles.items():
        assert step.variable == VARIABLE_FOR_ROLE[role]
        assert step.guid == guid_for(role)
        convert, add = step.commands
        assert convert.startswith("cert-to-efi-sig-list -g ")
        assert add.startswith("efi-sig-list -a ")


def test_build_enrollment_missing_cert_raises(tmp_path):
    keys = tmp_path / "keys"
    keys.mkdir()
    # Only PK.cert exists; KEK.cert and DB.cert are absent.
    (keys / "PK.cert").write_bytes(b"cert")
    with pytest.raises(EnrollmentError):
        build_enrollment(keys)


def test_build_enrollment_missing_dir_raises(tmp_path):
    with pytest.raises(EnrollmentError):
        build_enrollment(tmp_path / "does-not-exist")


# --- golden rendering -------------------------------------------------------


def test_shell_render_is_golden(tmp_path, monkeypatch):
    _make_keys_dir(tmp_path)
    monkeypatch.chdir(tmp_path)
    assert render_shell(build_enrollment(Path("keys"))) == GOLDEN_SHELL


def test_shell_output_is_runnable_sh(tmp_path, monkeypatch):
    # Every non-comment, non-blank line must be a well-formed shell command.
    _make_keys_dir(tmp_path)
    monkeypatch.chdir(tmp_path)
    for line in render_shell(build_enrollment(Path("keys"))).splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        shlex.split(line)  # raises on malformed tokens


def test_json_render_is_valid_and_complete(tmp_path, monkeypatch):
    _make_keys_dir(tmp_path)
    monkeypatch.chdir(tmp_path)
    data = json.loads(render_json(build_enrollment(Path("keys"))))
    assert [entry["role"] for entry in data["enrollment"]] == ["PK", "KEK", "DB"]
    for entry in data["enrollment"]:
        assert set(entry) == {
            "role",
            "variable",
            "guid",
            "cert",
            "sig",
            "commands",
        }
        assert entry["variable"] == VARIABLE_FOR_ROLE[entry["role"]]
        assert entry["guid"] == guid_for(entry["role"])
        assert entry["cert"].endswith(f"{entry['role']}.cert")
        assert entry["sig"].endswith(f"{entry['role']}.sig")
        assert entry["commands"][0].startswith("cert-to-efi-sig-list -g ")
        assert entry["commands"][1].startswith("efi-sig-list -a ")


# --- CLI integration --------------------------------------------------------


def test_cli_enroll_shell(tmp_path, capsys, monkeypatch):
    _make_keys_dir(tmp_path)
    monkeypatch.chdir(tmp_path)
    rc = cli.main(["enroll-commands", "--keys", "keys"])
    assert rc == 0
    assert capsys.readouterr().out == GOLDEN_SHELL


def test_cli_enroll_json(tmp_path, capsys, monkeypatch):
    _make_keys_dir(tmp_path)
    monkeypatch.chdir(tmp_path)
    rc = cli.main(["enroll-commands", "--keys", "keys", "--json"])
    assert rc == 0
    out = capsys.readouterr().out
    data = json.loads(out)
    assert len(data["enrollment"]) == 3


def test_cli_enroll_missing_cert_fails_closed(tmp_path, capsys, monkeypatch):
    keys = tmp_path / "keys"
    keys.mkdir()
    (keys / "PK.cert").write_bytes(b"cert")  # KEK/DB certs missing
    monkeypatch.chdir(tmp_path)
    rc = cli.main(["enroll-commands", "--keys", "keys"])
    assert rc == 1
    err = capsys.readouterr().err
    assert "error:" in err
    assert "missing certificate" in err


def test_cli_enroll_never_prints_key_material(tmp_path, capsys, monkeypatch):
    # Populate the key dir with a full set, then make sure no private-key
    # bytes leak into the shell or JSON output.
    keys = _make_keys_dir(tmp_path)
    # Drop a fake private key with recognizable bytes next to the certs.
    secret = b"PRIVATEKEYSECRET-MATERIAL-NOT-FOR-OUTPUT-1234567890"
    (keys / "PK.key").write_bytes(secret)
    monkeypatch.chdir(tmp_path)

    cli.main(["enroll-commands", "--keys", "keys"])
    shell = capsys.readouterr().out
    assert secret.decode() not in shell

    cli.main(["enroll-commands", "--keys", "keys", "--json"])
    js = capsys.readouterr().out
    assert secret.decode() not in js


