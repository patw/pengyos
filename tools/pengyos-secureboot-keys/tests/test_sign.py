# --- CLI integration --------------------------------------------------------


def test_cli_sign_shell(tmp_path, capsys, monkeypatch):
    _make_sign_files(tmp_path)
    monkeypatch.chdir(tmp_path)
    rc = cli.main(["sign", "uki.efi", "--key", "keys/DB.key"])
    assert rc == 0
    assert capsys.readouterr().out == GOLDEN_SHELL


def test_cli_sign_json(tmp_path, capsys, monkeypatch):
    _make_sign_files(tmp_path)
    monkeypatch.chdir(tmp_path)
    rc = cli.main(["sign", "uki.efi", "--key", "keys/DB.key", "--json"])
    assert rc == 0
    data = json.loads(capsys.readouterr().out)
    assert data["signing"]["commands"][0].startswith("sbsign ")


def test_cli_sign_missing_key_fails_closed(tmp_path, capsys, monkeypatch):
    _make_sign_files(tmp_path)
    (tmp_path / "keys" / "DB.key").unlink()
    monkeypatch.chdir(tmp_path)
    rc = cli.main(["sign", "uki.efi", "--key", "keys/DB.key"])
    assert rc == 1
    err = capsys.readouterr().err
    assert "error:" in err
    assert "missing signing key" in err


def test_cli_sign_never_prints_key_material(tmp_path, capsys, monkeypatch):
    _make_sign_files(tmp_path)
    # Drop a recognizable secret into the private key.
    secret = b"PRIVATEKEYSECRET-MATERIAL-NOT-FOR-OUTPUT-1234567890"
    (tmp_path / "keys" / "DB.key").write_bytes(secret)
    monkeypatch.chdir(tmp_path)

    cli.main(["sign", "uki.efi", "--key", "keys/DB.key"])
    shell = capsys.readouterr().out
    assert secret.decode() not in shell

    cli.main(["sign", "uki.efi", "--key", "keys/DB.key", "--json"])
    js = capsys.readouterr().out
    assert secret.decode() not in js


def test_cli_sign_execute_is_not_yet_implemented(capsys):
    # Actually running sbsign/sbverify is a future subtask.
    rc = cli.main(["sign", "uki.efi", "--key", "keys/DB.key", "--execute"])
    assert rc == cli.EXIT_NOT_YET_IMPLEMENTED
    captured = capsys.readouterr()
    assert "error:" in captured.err
    assert "DB.key" not in captured.out


# --- no-op guard ------------------------------------------------------------


def test_sign_error_importable():
    # Sanity: the error type the CLI depends on is importable.
    assert issubclass(SignError, RuntimeError)
