"""Generate UEFI Secure Boot enrollment commands.

This module turns the *public* certificates under a key directory into the
``sbsigntools`` commands that enroll PK/KEK/db into the firmware's EFI Secure
Boot variables:

* ``cert-to-efi-sig-list`` converts a certificate into an EFI signature list.
* ``efi-sig-list -a`` appends that signature to the matching EFI variable
  (``PK``, ``KEK`` or ``db``).

Only the certificates are ever read -- the private keys are never opened -- and
the rendered output never contains key material. GUIDs are derived
deterministically (see :func:`pengyos_sbkeys.keys.guid_for`), which is what
makes the generated commands golden-testable.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path
from typing import List, Optional, Sequence

from .keys import (
    KEY_FILES,
    KeyFile,
    is_private,
    guid_for,
    variable_for_role,
)
from .security import enforce_dir, PermCheckError

__all__ = [
    "EnrollStep",
    "EnrollmentError",
    "build_enrollment",
    "render_shell",
    "render_json",
    "enroll_commands",
]


class EnrollmentError(RuntimeError):
    """Raised when enrollment commands cannot be generated (e.g. a missing
    certificate)."""


@dataclass(frozen=True)
class EnrollStep:
    """One role's worth of enrollment: a cert converted to an EFI signature
    list and appended to the matching EFI variable."""

    role: str
    variable: str
    guid: str
    cert: Path
    sig: Path

    @property
    def convert_command(self) -> str:
        """``cert-to-efi-sig-list``: turn the cert into an EFI sig list file."""
        return (
            f"cert-to-efi-sig-list -g {self.guid} {self.cert} {self.sig}"
        )

    @property
    def add_command(self) -> str:
        """``efi-sig-list -a``: append the signature to the EFI variable."""
        return f"efi-sig-list -a {self.variable} {self.guid} {self.sig}"

    @property
    def commands(self) -> tuple[str, str]:
        """The two shell commands that enroll this role, in order."""
        return (self.convert_command, self.add_command)


def build_enrollment(keys_dir: Path) -> List[EnrollStep]:
    """Build the ordered enrollment steps for the key set under ``keys_dir``.

    The steps come out in Secure Boot enrollment order (PK, then KEK, then db).
    Raises :class:`EnrollmentError` if any required certificate is missing, and
    :class:`pengyos_sbkeys.security.PermCheckError` if any private key under
    ``keys_dir`` is more permissive than the policy allows (fail closed).
    """
    enforce_dir(keys_dir)
    steps: List[EnrollStep] = []
    for key_file in KEY_FILES:
        if is_private(key_file):
            continue
        role = key_file.role
        cert = keys_dir / key_file.name
        if not cert.is_file():
            raise EnrollmentError(
                f"missing certificate for role {role}: {cert} "
                "(run `pengyos-sbkeys init --out <dir>` first)"
            )
        sig = keys_dir / f"{Path(key_file.name).stem}.sig"
        steps.append(
            EnrollStep(
                role=role,
                variable=variable_for_role(role),
                guid=guid_for(role),
                cert=cert,
                sig=sig,
            )
        )
    return steps


def render_shell(steps: Sequence[EnrollStep]) -> str:
    """Render the enrollment steps as a runnable ``sh`` script."""
    lines: List[str] = [
        "#!/bin/sh",
        "# Generated by `pengyos-sbkeys enroll-commands`.",
        "# Enrolls the PengyOS PK/KEK/db Secure Boot keys into the firmware EFI",
        "# variables with sbsigntools. Run as root (prefix with sudo) on the",
        "# target machine.",
        "",
    ]
    for step in steps:
        lines.append(f"# --- Enroll {step.role} into {step.variable} ---")
        lines.append(
            f"# Convert {step.cert.name} to an EFI signature list ({step.sig.name})."
        )
        lines.append(step.convert_command)
        lines.append(
            f"# Append the signature to the {step.variable} EFI variable."
        )
        lines.append(step.add_command)
        lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"


def render_json(steps: Sequence[EnrollStep]) -> str:
    """Render the enrollment steps as a machine-readable JSON document."""
    data = {
        "enrollment": [
            {
                "role": step.role,
                "variable": step.variable,
                "guid": step.guid,
                "cert": str(step.cert),
                "sig": str(step.sig),
                "commands": list(step.commands),
            }
            for step in steps
        ]
    }
    return json.dumps(data, indent=2) + "\n"


def enroll_commands(keys_dir: Path, as_json: bool = False) -> str:
    """Build the enrollment for ``keys_dir`` and return it as text.

    When ``as_json`` is ``False`` the result is a shell script; otherwise it is
    a JSON document. Raises :class:`EnrollmentError` on any missing certificate
    and :class:`pengyos_sbkeys.security.PermCheckError` on insecure key perms.
    """
    steps = build_enrollment(Path(keys_dir))
    if as_json:
        return render_json(steps)
    return render_shell(steps)
