"""Generate ``sbsign`` / ``sbverify`` signing commands for a UKI.

This module turns a Unified Kernel Image (UKI), its signing key and certificate
into the ``sbsigntools`` commands that sign the image and then verify the
resulting signature:

* ``sbsign`` signs the UKI with the db private key and writes a signed copy.
* ``sbverify`` verifies the signature of the signed UKI against the certificate.

Only the file *paths* are ever referenced -- the private key is never opened
and its contents never appear in the rendered output. That is what makes the
generated commands golden-testable and keeps key material from leaking.

The commands are *generated*, not executed: unit tests never call ``sbsign`` or
``sbverify`` (they are mocked / avoided entirely). Actually running the tools is
a dedicated future subtask.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path
from typing import Optional

from .security import enforce_key, PermCheckError

__all__ = [
    "SignError",
    "Signing",
    "build_signing",
    "render_shell",
    "render_json",
    "sign_commands",
]


class SignError(RuntimeError):
    """Raised when signing commands cannot be generated (e.g. a missing key)."""


@dataclass(frozen=True)
class Signing:
    """A UKI to be signed with a signing key/certificate.

    Holds the *resolved* paths (default certificate, signed output) and knows
    how to render the two ``sbsigntools`` commands that sign and then verify the
    image.
    """

    uki: Path
    key: Path
    cert: Path
    out: Path

    @property
    def sbsign_command(self) -> str:
        """``sbsign``: sign the UKI with the db key into the signed output."""
        return (
            f"sbsign --key {self.key} --cert {self.cert} "
            f"--out {self.out} {self.uki}"
        )

    @property
    def sbverify_command(self) -> str:
        """``sbverify``: verify the signature of the signed UKI."""
        return f"sbverify --cert {self.cert} {self.out}"

    @property
    def commands(self) -> tuple[str, str]:
        """The two shell commands: sign, then verify, in order."""
        return (self.sbsign_command, self.sbverify_command)


def _default_cert_for(key: Path) -> Path:
    """Return the default certificate for a signing key.

    ``keys/DB.key`` -> ``keys/DB.cert`` (the key with a ``.cert`` suffix),
    matching the file layout :func:`pengyos_sbkeys.cli.cmd_init` writes.
    """
    return key.with_suffix(".cert")


def _signed_output_for(uki: Path, out: Optional[Path]) -> Path:
    """Return the signed-output path.

    Uses ``--out`` when given, otherwise derives ``<uki>.signed`` so the signed
    copy never overwrites the original image.
    """
    if out is not None:
        return out
    return Path(str(uki) + ".signed")


def build_signing(
    uki: Path,
    key: Path,
    cert: Optional[Path] = None,
    out: Optional[Path] = None,
) -> Signing:
    """Build the signing commands for ``uki`` signed with ``key``.

    ``cert`` defaults to ``key`` with a ``.cert`` suffix. ``out`` defaults to
    ``<uki>.signed``. Raises :class:`SignError` if the key, certificate or UKI
    does not exist (fail closed -- a command referencing a missing file is not
    useful) and :class:`pengyos_sbkeys.security.PermCheckError` if the signing
    key is a managed private key with more permissive bits than the policy
    allows.
    """
    uki = Path(uki)
    key = Path(key)
    cert = Path(cert) if cert is not None else _default_cert_for(key)
    out = _signed_output_for(uki, out)

    if not key.is_file():
        raise SignError(
            f"missing signing key: {key} "
            "(run `pengyos-sbkeys init --out <dir>` first)"
        )
    # Fail closed before signing: a private key with group/world bits is
    # considered compromised and must never be used to sign.
    enforce_key(key)
    if not cert.is_file():
        raise SignError(
            f"missing signing certificate: {cert} "
            "(run `pengyos-sbkeys init --out <dir>` first)"
        )
    if not uki.is_file():
        raise SignError(f"missing UKI: {uki}")

    return Signing(uki=uki, key=key, cert=cert, out=out)


def render_shell(signing: Signing) -> str:
    """Render the signing commands as a runnable ``sh`` script."""
    lines: list[str] = [
        "#!/bin/sh",
        "# Generated by `pengyos-sbkeys sign`.",
        "# Signs the PengyOS Unified Kernel Image with the db signing key via",
        "# sbsign, then verifies the resulting signature with sbverify.",
        "",
    ]
    lines.append(
        "# Sign the UKI with the db signing key, writing a signed copy."
    )
    lines.append(signing.sbsign_command)
    lines.append("# Verify the signature of the signed UKI.")
    lines.append(signing.sbverify_command)
    lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"


def render_json(signing: Signing) -> str:
    """Render the signing commands as a machine-readable JSON document."""
    data = {
        "signing": {
            "uki": str(signing.uki),
            "key": str(signing.key),
            "cert": str(signing.cert),
            "out": str(signing.out),
            "commands": list(signing.commands),
        }
    }
    return json.dumps(data, indent=2) + "\n"


def sign_commands(
    uki: Path,
    key: Path,
    cert: Optional[Path] = None,
    out: Optional[Path] = None,
    as_json: bool = False,
) -> str:
    """Build the signing commands for ``uki`` and return them as text.

    When ``as_json`` is ``False`` the result is a shell script; otherwise it is
    a JSON document. Raises :class:`SignError` on any missing file and
    :class:`pengyos_sbkeys.security.PermCheckError` on insecure key perms.
    """
    signing = build_signing(uki, key, cert, out)
    if as_json:
        return render_json(signing)
    return render_shell(signing)
