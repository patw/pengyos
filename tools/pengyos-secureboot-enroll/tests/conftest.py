"""Shared pytest fixtures for the ``pengyos_secureboot_enroll`` test suite.

The heart of this module is the *committed fixture tree* under
``tests/fixtures/`` -- a real, checked-in signed ESP plus its PK/KEK/db trust
root. It is the ground truth the round-trip is anchored to:

* ``tests/fixtures/keys/`` -- the PK/KEK/db key set (PEM certs + private keys),
  the Ed25519 verification-key sidecar, ``signatures.json`` and the db key id;
* ``tests/fixtures/signed_esp/`` -- the pinned boot-chain binaries, each signed.

It is generated by :mod:`tests.fixtures.build_fixtures` (which drives the real
library), so it stays reproducible and auditable rather than hand-fabricated.

The :func:`signed_fixture` fixture returns a *temp copy* of that tree (so tests
may mutate it without dirtying the committed copy), and :func:`fixture_keys`
returns the committed key dir read-only. :func:`foreign_key_set` builds a second
key set with a distinct ``db`` key id -- the honest model of a signer that is not
in ``db``.
"""

from __future__ import annotations

import base64
import os
import shutil
from dataclasses import dataclass
from pathlib import Path

import pytest

# tests/fixtures/ lives at <repo>/tests/fixtures/, so the repo root is three
# parents up.
FIXTURES_ROOT = Path(__file__).resolve().parent.parent / "tests" / "fixtures"
FIXTURE_KEYS = FIXTURES_ROOT / "keys"
FIXTURE_ESP = FIXTURES_ROOT / "signed_esp"


@dataclass
class SignedFixture:
    """A temp copy of the committed signed fixture tree.

    :attr:`keys_dir` holds the trust root + ``signatures.json``; :attr:`esp_dir`
    holds the signed ESP. Mutating these is safe -- they are copies, not the
    committed fixtures.
    """

    keys_dir: Path
    esp_dir: Path

    @property
    def signatures(self) -> Path:
        return self.keys_dir / "signatures.json"


@pytest.fixture
def fixture_keys() -> Path:
    """The committed key dir, read-only (do not mutate -- pass a copy)."""
    return FIXTURE_KEYS


@pytest.fixture
def signed_fixture(tmp_path) -> SignedFixture:
    """Return a writable temp copy of the committed signed fixture tree.

    Git only tracks the *executable* bit, so the committed private keys check
    out as ``0644`` even though the generator writes them ``0600`` (dirs
    ``0700``). The fixture is meant to be a *strict* trust root -- the CLI
    ``lint``/``enroll`` paths refuse to run against loose key permissions -- so
    we restore the generator's mode bits on the copy here. Without this the
    round-trip tests fail on any fresh checkout while passing in the loop's
    sandbox (where the fixtures were generated in place).
    """
    dest = tmp_path / "signed_fixture"
    shutil.copytree(FIXTURES_ROOT, dest)
    keys_dir = dest / "keys"
    keys_dir.chmod(0o700)
    for role in ("PK", "KEK", "DB"):
        (keys_dir / f"{role}.key").chmod(0o600)
        (keys_dir / f"{role}.cert").chmod(0o644)
    return SignedFixture(keys_dir=keys_dir, esp_dir=dest / "signed_esp")


def _make_pem(body: bytes) -> bytes:
    """Wrap ``body`` in a single-cert PEM with correct base64 padding."""
    b64 = base64.b64encode(body).decode("ascii")
    wrapped = "\n".join(b64[i : i + 64] for i in range(0, len(b64), 64))
    return f"-----BEGIN CERTIFICATE-----\n{wrapped}\n-----END CERTIFICATE-----\n".encode("utf-8")


def foreign_key_set(root: Path, suffix: str = "FOREIGN") -> Path:
    """Write a second PK/KEK/db key set with a *distinct* ``db`` key id.

    The certs differ from the committed fixture (``{role}-{suffix}``), so the
    ``db`` fingerprint -- and therefore the key id -- is different. This is the
    honest model of a signing key that is not present in ``db``: a binary signed
    by this key cannot be trusted by the primary trust root. Returns the path.
    """
    keys_dir = root / f"foreign-{suffix}"
    keys_dir.mkdir(parents=True, exist_ok=True)
    for role in ("PK", "KEK", "DB"):
        cert = keys_dir / f"{role}.cert"
        cert.write_bytes(_make_pem(f"CERT-{role}-{suffix}".encode()))
        cert.chmod(0o644)
        key = keys_dir / f"{role}.key"
        key.write_bytes(f"PRIVATE-KEY-{role}-{suffix}".encode())
        key.chmod(0o600)
    keys_dir.chmod(0o700)
    return keys_dir


# Keep ``os`` importable for callers that pass str paths; the helpers above take
# Path, but a couple of tests still build paths with ``os.path``.
__all__ = [
    "FIXTURES_ROOT",
    "FIXTURE_KEYS",
    "FIXTURE_ESP",
    "SignedFixture",
    "fixture_keys",
    "signed_fixture",
    "foreign_key_set",
]
