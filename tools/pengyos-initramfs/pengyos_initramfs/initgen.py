"""Minimal ``/init`` generator for ``pengyos-initramfs``.

Every initramfs needs a program to hand off to after the kernel unpacks the
archive into the initial RAM filesystem (``/init``). This module generates a
*minimal, deterministic* POSIX ``sh`` script for that role:

* The content is a **pure function of the spec** — it contains no wall-clock
  timestamps, host names, or environment-dependent values, so it never breaks
  the byte-reproducibility of the archive.
* The archive entry's **path** and **mode** come from the spec's ``[init]``
  table (``path`` default ``"init"``, ``mode`` default ``0o755``).

Behavior of the generated script (classic rescue-initramfs semantics):

1. ``set -eu`` — fail loudly.
2. Create ``/proc``, ``/sys``, ``/dev`` (the kernel does not create mount
   points during initramfs extraction) and mount the early virtual
   filesystems (``proc``, ``sysfs``, ``devtmpfs``).
3. ``exec /bin/sh`` — hand control to an interactive shell.

The generated entry is a *regular file* packed with the spec's normalized
``init.mode``; the builder (``builder.py``) is responsible for adding it to
the archive in the canonical sorted position. If the operator *explicitly*
lists ``init.path`` in an include list (``binaries``/``files``/``modules``),
the real file from the root wins and no script is generated (see spec.md).
"""

from __future__ import annotations

from .spec import Spec

__all__ = ["generate_init_script", "init_entry_bytes", "init_entry_mode", "INIT_SCRIPT"]

_S_IFREG = 0o100000

#: The minimal init script (POSIX sh). Pure function of the spec: no
#: timestamps or environment-dependent values may be added.
INIT_SCRIPT = """\
#!/bin/sh
# PengyOS minimal init -- generated by pengyos-initramfs (do not edit by hand).
# The content is deterministic: a pure function of the spec, with no
# timestamps or environment-dependent values.

set -eu

# Create the mount points (the kernel does not create them during initramfs
# extraction) and mount the early virtual filesystems.
mkdir -p /proc /sys /dev
mount -t proc     proc     /proc
mount -t sysfs    sysfs    /sys
mount -t devtmpfs devtmpfs /dev

# Hand control over to an interactive shell (classic rescue-initramfs behavior).
exec /bin/sh
"""


def init_entry_mode(spec: Spec) -> int:
    """The cpio mode for the generated init entry (regular file + ``spec.init_mode``)."""
    return _S_IFREG | (spec.init_mode & 0o7777)


def generate_init_script(spec: Spec) -> str:
    """Return the script text that becomes the archive's ``spec.init_path`` entry.

    Deterministic: the same spec always yields the same text (in fact the
    template is fixed, so any two specs yield the same text).
    """
    return INIT_SCRIPT


def init_entry_bytes(spec: Spec) -> bytes:
    """Return the exact data bytes for the generated init entry."""
    return generate_init_script(spec).encode("ascii")
