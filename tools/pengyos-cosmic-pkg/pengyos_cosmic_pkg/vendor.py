"""``vendor`` — deterministic, git-dependency-aware vendoring.

Given a component manifest (URL + pinned tag + license/flags), the workspace's
``Cargo.lock`` and a local mirror of the checked-out git crates, produce a
**deterministic** vendored source tree, rewriting every ``git = "..."`` source
in the lock to a path into the vendored tree, and emitting the source ``.hash``
in Buildroot's format.

### What the vendored tree looks like

::

    <out>/
    ├── Cargo.lock                 # rewritten: git source -> path:VENDOR/<name>
    ├── .cargo/
    │   └── config.toml            # [source.<id>] -> directory = "VENDOR/<name>"
    ├── VENDOR/
    │   └── <dep-name>/            # each git dep's source, copied from
    │       ├── Cargo.toml
    │       └── src/...
    ├── <name>-<version>.tar.gz    # deterministic tarball of the vendored tree
    └── <name>.hash                # Buildroot-format sha256 of that tarball

This mirrors what Buildroot's ``cargo vendor`` post-process produces (a
``VENDOR/`` directory plus a ``.cargo/config.toml`` that points cargo at it),
except it runs offline against a committed mirror of the git crates instead of
cloning them over the network.

### Determinism

The tree is byte-for-byte reproducible for a given set of inputs:

* the rewritten ``Cargo.lock`` and ``.cargo/config.toml`` are generated text,
  with git-source entries emitted in sorted-by-package-name order;
* each copied crate is written with a normalised file ordering (paths sorted);
* the tarball is written with normalised metadata (mtime/uid/gid/uname/gname
  zeroed, directories ``0755``) and a sorted member order, so the ``.hash`` is
  stable across runs and machines.

"""

from __future__ import annotations

import gzip
import hashlib
import json
import tarfile
from dataclasses import dataclass, field
from pathlib import Path

from .cargo import CargoLock, CargoPackage, load_lock, git_slug
from .manifest import ComponentManifest, ManifestError, load_manifest

#: Directory name (inside the vendored tree) that holds the vendored deps.
VENDOR_DIRNAME = "VENDOR"
#: The cargo config file name (inside ``.cargo/``).
CARGO_CONFIG_REL = ".cargo/config.toml"
#: The tarball suffix for the vendored source.
TAR_SUFFIX = ".tar.gz"
#: The Buildroot hash line format: "<type>  <hash>  <filename>".
_HASH_LINE_FMT = "%s  %s  %s\n"


@dataclass
class VendResult:
    """The outcome of a :func:`vend` run: what was written and the hash."""

    out_dir: Path
    lock_path: Path
    cargo_config_path: Path
    vendored_dir: Path
    tarball_path: Path
    hash_path: Path
    hash_type: str
    hash_filename: str
    hash_value: str
    git_packages: list[str] = field(default_factory=list)

    def hash_line(self) -> str:
        """The single Buildroot-format line written to the ``.hash`` file."""
        return _HASH_LINE_FMT % (self.hash_type, self.hash_value, self.hash_filename)

    def summary(self) -> dict[str, object]:
        """A JSON-serialisable summary of the vendored tree."""
        return {
            "out_dir": str(self.out_dir),
            "hash_type": self.hash_type,
            "hash_value": self.hash_value,
            "hash_filename": self.hash_filename,
            "git_packages": self.git_packages,
            "tarball": str(self.tarball_path.name),
            "files": [str(p.relative_to(self.out_dir)) for p in self._walk()],
        }

    def _walk(self) -> list[Path]:
        out = list(self.vendored_dir.rglob("*"))
        out += [self.lock_path, self.cargo_config_path]
        return sorted(p for p in out if p.is_file())


def _rewrite_lock(lock: CargoLock) -> str:
    """Render a ``Cargo.lock`` with every git source rewritten to a path.

    The root ``[package]`` and registry packages are emitted verbatim; each
    git package's ``source`` becomes ``path:VENDOR/<name>`` (the vendored copy)
    and its ``#<sha>`` fragment is dropped. Entries are emitted in the original
    lockfile order so the output is a stable reflection of the input.
    """
    lines: list[str] = ["# This file is generated by pengyos-cosmic-pkg vendor.", "# git sources are rewritten to path:VENDOR/<name>.", ""]
    for pkg in lock.packages:
        lines.append("[package]")
        lines.append(f'name = "{pkg.name}"')
        lines.append(f'version = "{pkg.version}"')
        if pkg.kind == "git":
            # Rewrite the git source to the vendored path (fragment dropped).
            lines.append(f'source = "path:{VENDOR_DIRNAME}/{pkg.name}"')
        elif pkg.kind == "registry":
            lines.append(f'source = "registry+{pkg.registry_index}"')
            if pkg.checksum:
                lines.append(f'checksum = "{pkg.checksum}"')
        # root and path packages: no source field, emitted as-is.
        lines.append("")
    return "\n".join(lines) + "\n"


def _render_cargo_config(lock: CargoLock) -> str:
    """Render the ``.cargo/config.toml`` that points cargo at the vendored tree.

    Mirrors ``cargo vendor`` output: crates.io is replaced with the vendored
    sources directory, and each git source is mapped to its own
    ``VENDOR/<name>`` directory. Git-source entries are emitted in sorted
    package-name order for determinism.
    """
    lines: list[str] = [
        "# Generated by pengyos-cosmic-pkg vendor.",
        "[source.crates-io]",
        "replace-with = \"vendored-sources\"",
        "",
        "[source.vendored-sources]",
        f'directory = "{VENDOR_DIRNAME}"',
    ]
    for pkg in sorted(lock.git_packages(), key=lambda p: p.name):
        lines.append("")
        lines.append(f'[source.{pkg.git.source_id}]')
        lines.append(f'directory = "{VENDOR_DIRNAME}/{pkg.name}"')
    return "\n".join(lines) + "\n"


def _copy_tree(src: Path, dst: Path) -> None:
    """Copy ``src`` into ``dst`` deterministically (sorted file order)."""
    dst.mkdir(parents=True, exist_ok=True)
    entries = sorted(src.rglob("*"), key=lambda p: p.relative_to(src).as_posix())
    for entry in entries:
        rel = entry.relative_to(src)
        target = dst / rel
        if entry.is_dir():
            target.mkdir(parents=True, exist_ok=True)
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(entry.read_bytes())


def _tar_normalise(ti: tarfile.TarInfo) -> tarfile.TarInfo:
    """Normalise a tar member for reproducible output.

    File modes come from the filesystem (umask-dependent), so force them too:
    directories ``0755``, files ``0644``. Combined with the zeroed mtime/uid/gid
    and sorted member order this makes the tarball byte-for-byte reproducible
    across machines, not just repeated runs on the same one.
    """
    ti.mtime = 0
    ti.uid = ti.gid = 0
    ti.uname = ti.gname = ""
    if ti.isdir():
        ti.mode = 0o755
    elif ti.isfile():
        ti.mode = 0o644
    return ti


def _deterministic_tarball(
    root: Path,
    tarball: Path,
    exclude: set[str],
    *,
    prefix: str | None = None,
) -> None:
    """Write a byte-for-byte reproducible tarball of ``root``.

    Every member (directories and files) is emitted with sorted paths and
    normalised metadata (mtime/uid/gid/uname/gname zeroed, directories forced to
    ``0755``). Members whose basename is in ``exclude`` (the tarball itself and
    the ``.hash``) are skipped.

    When ``prefix`` is given, every member's arcname is rooted under a single
    top-level ``<prefix>/`` directory. Buildroot extracts a package tarball to a
    single ``<name>-<version>/`` directory and its ``cargo`` download
    post-process recognises an *already-vendored* tarball by grepping its member
    list for a ``VENDOR/`` directory nested under exactly one top-level
    component (``grep -q "^[^/]*/VENDOR"``). Wrapping the vendored tree in
    ``<name>-<version>/`` therefore makes the tarball self-recognising to
    Buildroot: it skips re-running ``cargo vendor`` (which would fail offline and
    rewrite the tree) and uses the vendored sources as-is.
    """
    root = root.resolve()
    entries = sorted(root.rglob("*"), key=lambda p: p.relative_to(root).as_posix())

    # A GzipFile with mtime=0 keeps the gzip header timestamp fixed, so the
    # compressed tarball is byte-for-byte reproducible (gzip otherwise stamps
    # the current time into its header).
    with open(tarball, "wb") as raw:
        with gzip.GzipFile(fileobj=raw, mode="wb", mtime=0) as gz:
            with tarfile.open(fileobj=gz, mode="w") as tar:
                for path in entries:
                    if path.name in exclude:
                        continue
                    arcname = path.relative_to(root).as_posix()
                    if prefix:
                        arcname = f"{prefix}/{arcname}"
                    info = tar.gettarinfo(str(path), arcname=arcname)
                    info = _tar_normalise(info)
                    if info.isfile():
                        with path.open("rb") as fh:
                            tar.addfile(info, fh)
                    else:
                        tar.addfile(info)


def _sha256_tarball(tarball: Path) -> str:
    h = hashlib.sha256()
    with tarball.open("rb") as fh:
        for chunk in iter(lambda: fh.read(65536), b""):
            h.update(chunk)
    return h.hexdigest()


def vend(
    manifest: ComponentManifest,
    lock: CargoLock,
    git_sources_root: Path | str,
    out_dir: Path | str,
    *,
    hash_type: str = "sha256",
) -> VendResult:
    """Produce a deterministic vendored source tree.

    * ``manifest`` — the component being vendored (for the hash filename).
    * ``lock`` — the parsed ``Cargo.lock`` (git sources will be rewritten).
    * ``git_sources_root`` — the local mirror of checked-out git crates, keyed by
      slug (see :func:`cargo.git_slug`).
    * ``out_dir`` — where to write the vendored tree.

    Raises :class:`ManifestError` (via :class:`CargoLockError`) when a git
    source has no checked-out copy in the mirror.
    """
    git_sources_root = Path(git_sources_root)
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    git_pkgs = lock.git_packages()
    if not git_pkgs:
        raise ManifestError(
            "no git-sourced packages in Cargo.lock to vendor; "
            "nothing to rewrite"
        )

    # 1. Rewrite the lock and write it into the vendored tree.
    vendored_root = out_dir
    lock_path = vendored_root / "Cargo.lock"
    lock_path.write_text(_rewrite_lock(lock), encoding="utf-8")

    # 2. Render and write the cargo config.
    cargo_config_path = vendored_root / CARGO_CONFIG_REL
    cargo_config_path.parent.mkdir(parents=True, exist_ok=True)
    cargo_config_path.write_text(_render_cargo_config(lock), encoding="utf-8")

    # 3. Copy each git dep's checked-out source into VENDOR/<name>/.
    vendored_dir = vendored_root / VENDOR_DIRNAME
    vendored_dir.mkdir(parents=True, exist_ok=True)
    for pkg in sorted(git_pkgs, key=lambda p: p.name):
        if pkg.git is None:  # pragma: no cover - guarded by git_packages()
            raise ManifestError(f"{pkg.name}: git package without a source")
        slug = git_slug(pkg.git.url)
        src = git_sources_root / slug
        if not src.is_dir():
            raise ManifestError(
                f"no checked-out source for git dep '{pkg.name}' "
                f"(git_url={pkg.git.url!r}); expected {src}"
            )
        _copy_tree(src, vendored_dir / pkg.name)

    # 4. Deterministically tarball the vendored tree and hash it.
    tarball_name = f"{manifest.name}-{manifest.version}{TAR_SUFFIX}"
    hash_name = f"{manifest.name}.hash"
    tarball_path = vendored_root / tarball_name
    # Exclude the generated outputs themselves (by basename) so that re-running
    # into the same dir does not fold a stale tarball/.hash into the tree and
    # change the hash -- the whole point of "deterministic".
    #
    # The tarball is wrapped in a single top-level `<name>-<version>/` directory
    # (the Buildroot extraction convention): Buildroot's cargo download
    # post-process recognises an already-vendored tarball by grepping its member
    # list for a `VENDOR/` dir nested under exactly one top-level component, so
    # this wrapper makes the tarball self-recognising and skips re-vendoring.
    _deterministic_tarball(
        vendored_root,
        tarball_path,
        {tarball_name, hash_name},
        prefix=f"{manifest.name}-{manifest.version}",
    )
    hash_value = _sha256_tarball(tarball_path)

    hash_path = vendored_root / f"{manifest.name}.hash"
    hash_path.write_text(
        _HASH_LINE_FMT % (hash_type, hash_value, tarball_name),
        encoding="utf-8",
    )

    return VendResult(
        out_dir=out_dir,
        lock_path=lock_path,
        cargo_config_path=cargo_config_path,
        vendored_dir=vendored_dir,
        tarball_path=tarball_path,
        hash_path=hash_path,
        hash_type=hash_type,
        hash_filename=tarball_name,
        hash_value=hash_value,
        git_packages=[p.name for p in git_pkgs],
    )


def _emit(args, result: VendResult) -> int:
    """Print the vendor result (human or JSON) and return the exit code.

    The JSON envelope is uniform with the CLI's error envelope: every JSON
    response carries ``command`` and ``ok`` (``True`` here, ``False`` plus an
    ``error`` on failure), so a consumer can dispatch on ``ok`` alone.
    """
    if getattr(args, "json", False):
        payload = result.summary()
        payload.update({"command": args.command, "ok": True})
        print(json.dumps(payload, indent=2, sort_keys=True))
    else:
        print(
            f"Vendored {len(result.git_packages)} git "
            f"package(s) into {result.out_dir}"
        )
        for name in result.git_packages:
            print(f"  - {name} -> {VENDOR_DIRNAME}/{name}")
        print(f"Source hash: {result.hash_type} {result.hash_value} "
              f"{result.hash_filename}")
    return 0


def main(args) -> int:
    """CLI entry point for ``vendor``."""
    manifest = load_manifest(args.manifest)
    lock = load_lock(args.cargo_lock)
    git_sources = (
        Path(args.cargo_lock).parent / "git-sources"
        if args.git_sources is None
        else args.git_sources
    )
    result = vend(
        manifest,
        lock,
        git_sources,
        args.out,
    )
    return _emit(args, result)
