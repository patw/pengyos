"""Deterministic rendering of the default-deny Server ruleset (US-SRV-5).

The ``rules`` command (see :mod:`pengyos_netctl.cli`) renders an
``nftables`` ruleset from a :class:`~pengyos_netctl.config.PortsConfig`
declared-ports spec. The output is *deterministic*: the same config always
produces byte-identical text, so the rendered file is reproducible and can
be committed and diffed cleanly.

The rendered ruleset:

* begins with ``flush ruleset`` (nothing pre-existing leaks in),
* installs a single ``table inet filter`` with ``input``/``forward``/
  ``output`` chains,
* sets ``input`` and ``forward`` to ``policy drop`` (default-deny) and
  ``output`` to ``policy accept``,
* mitigates SSH brute-force with an sshguard/fail2ban-style rate-limit
  (new connections beyond the threshold are dropped — an automatic ban),
* allows inbound **only** the declared ports — SSH (tcp) + WireGuard
  (udp) + the ports named in the config — no more, no less.

The result is guaranteed to satisfy the offline validator in
:mod:`pengyos_netctl.nft` (:func:`validate_ports_ruleset_text`); the
``rules`` command validates the rendered text before writing it to disk.
"""

from __future__ import annotations

import os
from typing import List

from .config import PortsConfig
from .nft import validate_ports_ruleset_text

__all__ = [
    "render_ports_ruleset",
    "render_allow_list",
    "render_ports",
    "mitigation_statements",
    "write_ruleset",
]


# The fixed skeleton shared by every rendered ruleset. ``{{PORTS}}`` is the
# human-readable port list in the header comment; ``{{MITIGATION}}`` is the
# sshguard/fail2ban-style SSH rate-limit/ban body; ``{{ALLOW}}`` is the
# generated allow-list body inside the ``input`` chain. Everything else is
# literal — the only three placeholders in the template.
_RULESET_TEMPLATE = """#!/usr/sbin/nft -f

# PengyOS server-firewall ruleset (US-SRV-5).
# Generated by `pengyos-netctl rules`; policy: default-deny inbound,
# only the declared ports exposed.
#
#   input  : policy drop
#   forward: policy drop
#   output : policy accept
#
# Declared inbound ports (see nftables/ports.yaml):
{{PORTS}}

flush ruleset

table inet filter {

    chain input {
        type filter hook input priority 0; policy drop;

        # Never drop our own traffic.
        iif "lo" accept

        # Stateful: continue established/related flows.
        ct state established,related accept

        # Drop malformed packets before any policy decision.
        ct state invalid drop

        # SSH brute-force mitigation (sshguard/fail2ban-style): drop new
        # SSH connections beyond the rate — an automatic ban of repeat
        # offenders. Placed *before* the allow list so an overflowing
        # connection is dropped instead of accepted.
{{MITIGATION}}
        # Allow list: declared ports only.
{{ALLOW}}
    }

    chain forward {
        type filter hook forward priority 0; policy drop;
    }

    chain output {
        type filter hook output priority 0; policy accept;
    }
}
"""


def _port_label(proto: str, port: int, ports: PortsConfig) -> str:
    """A short human label for a declared port in the header comment."""
    if proto == "tcp" and port == ports.ssh_port:
        return "SSH (always allowed)"
    if proto == "udp" and port == ports.listen_port:
        return "WireGuard (always allowed)"
    return "(declared)"


def render_ports(ports: PortsConfig) -> str:
    """Render the ``# Declared inbound ports`` header list for ``ports``.

    Deterministic: tcp ports (incl. SSH) first, then udp (incl. WireGuard),
    each in ascending numeric order, exactly mirroring the allow list.
    """
    allow = ports.allow_list()  # {"tcp": [...], "udp": [...]}
    lines: List[str] = []
    for proto in ("tcp", "udp"):
        for p in allow[proto]:
            lines.append(f"#   {proto:<3} {p:<5} {_port_label(proto, p, ports)}")
    return "\n".join(lines)


def render_allow_list(ports: PortsConfig) -> str:
    """Render the ``input`` chain allow-list statements for ``ports``.

    One ``<proto> dport <port> accept`` per declared port, tcp first then
    udp, ascending — so the rendered file is byte-for-byte deterministic.
    """
    allow = ports.allow_list()
    lines: List[str] = []
    for proto in ("tcp", "udp"):
        for p in allow[proto]:
            lines.append(f"        {proto} dport {p} accept")
    return "\n".join(lines)


# The sshguard/fail2ban-style SSH brute-force mitigation. New SSH connections
# beyond this rate are dropped — an automatic "ban" of repeat offenders. It is
# emitted before the allow list so an overflowing connection is dropped
# rather than accepted (the allow-list `accept` would otherwise win).
#
#   tcp dport <ssh_port> ct state new limit rate over 3/minute burst 5 packets drop
#
# A single, fixed rule keeps the ruleset deterministic and the validator's
# assertion simple. It references the configured ``ssh_port`` so it stays
# correct if that port is ever changed.
SSH_RATE_LIMIT_TEMPLATE = (
    "        tcp dport {ssh_port} ct state new "
    "limit rate over 3/minute burst 5 packets drop"
)


def mitigation_statements(ports: PortsConfig) -> str:
    """Render the sshguard/fail2ban-style SSH rate-limit/ban for ``ports``.

    One statement: new SSH connections beyond ``3/minute`` (a 5-packet
    burst) are dropped. Deterministic — the same config always yields the
    same text.
    """
    return SSH_RATE_LIMIT_TEMPLATE.format(ssh_port=ports.ssh_port)


def render_ports_ruleset(ports: PortsConfig) -> str:
    """Return the full, validated default-deny ruleset for ``ports``.

    The text is deterministic and always passes
    :func:`pengyos_netctl.nft.validate_ports_ruleset_text` for the same
    ``ports`` (the generator validates before writing to disk).
    """
    ports_block = render_ports(ports)
    mitigation_block = mitigation_statements(ports)
    allow_block = render_allow_list(ports)
    ruleset = (
        _RULESET_TEMPLATE.replace("{{PORTS}}", ports_block)
        .replace("{{MITIGATION}}", mitigation_block)
        .replace("{{ALLOW}}", allow_block)
    )
    result = validate_ports_ruleset_text(ruleset, ports)
    if not result.ok:
        # Should never happen — the renderer is built to satisfy the policy.
        # If it does, surface the violations loudly rather than emit a
        # ruleset that fails validation.
        raise RuntimeError(
            "rendered ruleset failed validation: " + "; ".join(result.errors)
        )
    return ruleset


def write_ruleset(path: str, text: str) -> str:
    """Write ``text`` to ``path`` (creating parent dirs) and return ``path``.

    Raises :class:`OSError` on a write failure so the caller can translate
    it into a clean user-facing error.
    """
    parent = os.path.dirname(os.path.abspath(path))
    if parent:
        os.makedirs(parent, exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(text)
        if not text.endswith("\n"):
            fh.write("\n")
    return path
